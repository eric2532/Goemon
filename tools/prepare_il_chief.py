"""Part-specific native paint for the Il chief; the recovered master remains unchanged."""
import argparse
import hashlib
import io
import json
from pathlib import Path
from PIL import Image
from build_village_building_surfaces import surface_atlas

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'build/Other Files/Asset Toolkit/Il and Laruka/Source/11268.png'
OUTPUT = ROOT / 'assets/maps/falan/il_chief'
PATCHES = {
    'plaster': (11268, [(238,320),(256,309),(256,350),(238,361)], False, (48,96)),
    'timber': (11268, [(145,391),(175,391),(175,414),(145,414)], False, (32,96)),
    'stone': (11268, [(172,452),(186,461),(186,473),(172,464)], False, (64,80)),
    'stone_cap': (11268, [(129,424),(148,437),(162,427),(143,414)], False, (80,64)),
    'thatch': (11272, [(79,185),(128,220),(151,201),(102,165)], False, (96,64)),
    'dark_thatch': (11268, [(240,162),(271,179),(272,206),(239,190)], False, (80,80)),
    'window': (11268, [(156,323),(196,323),(196,368),(156,368)], True, (80,90)),
    'upper_window': (11268, [(166,139),(184,139),(184,174),(166,174)], True, (48,96)),
    'door': (11268, [(73,288),(113,315),(113,388),(73,361)], True, (48,100)),
    'sign': (11268, [(260,253),(285,238),(303,252),(279,270)], True, (96,80)),
}


def artifacts():
    source = Image.open(SOURCE).convert('RGBA')
    assert source.size == (344, 522)
    assert hashlib.sha256(source.tobytes()).hexdigest() == 'f25739c0e26cca871c8cb10b68bfa5798391a58db142ef9382299ada767c7196'
    neighbor_path = SOURCE.with_name('11272.png')
    neighbor = Image.open(neighbor_path).convert('RGBA')
    catalog_line = next(line for line in (ROOT/'assets/maps/falan/il_laruka/data.gd').read_text().splitlines() if line.startswith('const GRAPHICS='))
    neighbor_record = json.loads(catalog_line.split('=',1)[1])['11272']
    assert hashlib.sha256(neighbor.tobytes()).hexdigest() == neighbor_record['rgba_sha256']
    atlas, rows = surface_atlas({11268: source,11272:neighbor}, PATCHES)
    shared = Image.open(ROOT/'assets/maps/falan/il_laruka/building-surfaces.png').convert('RGBA')
    assert atlas.crop((0,128,128,256)).tobytes() == shared.crop((128,0,256,128)).tobytes(), 'Reused thatch tile changed'
    png = io.BytesIO(); atlas.save(png, format='PNG', optimize=True)
    rows[1] = '## Generated by tools/prepare_il_chief.py; separate native chief-building parts.'
    proof = {'source_graphic':11268, 'source_map':2000, 'source_cell':[48,86],
             'source_rgba_sha256':hashlib.sha256(source.tobytes()).hexdigest(),
             'source_path':str(SOURCE.relative_to(ROOT)), 'source_footprint':[6,7],
             'source_door_cell':[47,83], 'patches':PATCHES,
             'runtime_height_frame':{'village_world_per_source_pixel':0.045, 'reference_only':'The isolated source-axis fit uses the city Euclidean projection before applying the existing village height frame; actual village captures use that .045world/pixel adaptation.'},
             'inferred_back_roof_paint':{'source_graphic':11272,'rgba_sha256':neighbor_record['rgba_sha256'],'reused_prepared_tile':'assets/maps/falan/il_laruka/building-surfaces.png::thatch','reason':'The compatible existing village straw tile avoids projecting chief-front details onto unseen slopes.'},
             'front_copy':'front.png retains the exact transparent native master; the existing shared opaque atlas is unchanged.',
             'inferred':['Hidden roof slopes and rear plaster/timber carry native part paint at fixed world scale.',
                         'Stone-block depth, thatch thickness, supporting rafters, rear window rhythm and vane thickness are reconstructed from the visible design.',
                         'No additional doors, rooms, routes or collision owners are created.']}
    return {'front.png':SOURCE.read_bytes(), 'surfaces.png':png.getvalue(), 'surfaces.gd':('\n'.join(rows+['}'])+'\n').encode(),
            'provenance.json':(json.dumps(proof,ensure_ascii=False,indent=2)+'\n').encode()}


def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true');args=parser.parse_args()
    products=artifacts()
    if args.check:
        assert all((OUTPUT/name).read_bytes()==data for name,data in products.items()), 'Stale Il chief derivative'
        print('Il chief native-source derivatives are current; master RGBA verified.')
    else:
        OUTPUT.mkdir(parents=True,exist_ok=True)
        for name,data in products.items(): (OUTPUT/name).write_bytes(data)
        print('Prepared 10 isolated chief-building native paint parts; master unchanged.')

if __name__=='__main__':main()
