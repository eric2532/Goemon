"""Village-only painted surface derivatives; preserve the recovered masters."""
import hashlib
import json
import re
from pathlib import Path
from PIL import Image, ImageFilter, ImageStat

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets/maps/falan/tina/street_art"
SOURCE = ROOT / "assets/maps/original_crossgate/building-surfaces.png"


def main():
    OUT.mkdir(exist_ok=True)
    source = Image.open(SOURCE).convert("RGBA")
    table = (SOURCE.parent / "building-surfaces.gd").read_text()
    recipes = {"wood":"tina_box_plank", "trim":"tina_fence_wood", "stone":"tina_ruin_stone",
               "snowroof":"tina_soft_snow", "blue":"blue_roof", "green":"green_roof",
               "brown":"brown_roof", "door":"tina_round_door", "pub_door":"tina_pub_door",
               "sign":"tina_pub_sign", "plaster":"plaster", "log":"tina_log_bark"}
    atlas = Image.new("RGBA", (512,384))
    lines = ["extends RefCounted", "## Generated by tools/prepare_tina_village_art.py.", "const TILES={"]
    for index, (name, original) in enumerate(recipes.items()):
        match = re.search('"'+original+r'":Vector2\((\d+),(\d+)\)', table)
        x,y = map(int, match.groups())
        patch = source.crop((x+8,y+8,x+120,y+120))
        if name not in ["door","pub_door","sign"]:
            patch = patch.filter(ImageFilter.GaussianBlur(1.1))
            tone = tuple(round(v) for v in ImageStat.Stat(patch).mean[:3])+(255,)
            patch = Image.blend(patch, Image.new("RGBA", patch.size, tone), .55 if name in ["wood","trim","stone","log"] else .25)
        padded = patch.resize((128,128), Image.Resampling.NEAREST)
        padded.paste(patch,(8,8))
        pixels=padded.load();inside=patch.load()
        for py in range(128):
            for px in range(128):
                if px<8 or py<8 or px>=120 or py>=120:pixels[px,py]=inside[min(111,max(0,px-8)),min(111,max(0,py-8))]
        atlas.paste(padded,(index%4*128,index//4*128))
        lines.append(f' "{name}":Vector2({index%4*128},{index//4*128}),')
    lines.append("}")
    atlas.save(OUT / "materials.png")
    (OUT / "materials.gd").write_text("\n".join(lines)+"\n")
    # Same UV layout as the existing terrain atlas; only the scoped street owner uses it.
    ground_source=ROOT / "assets/maps/falan/tina/ground.png"
    ground=Image.open(ground_source).convert("RGBA")
    records=json.loads((ground_source.parent / "ground.json").read_text())["graphics"]
    for record in records.values():
        x,y,w,h=record["rect"]
        tile=ground.crop((x,y,x+w,y+h))
        low=tile.resize((16,12),Image.Resampling.BOX).resize((w,h),Image.Resampling.BICUBIC)
        tile=Image.blend(tile.filter(ImageFilter.GaussianBlur(.85)),low,.55)
        ground.paste(tile,(x,y))
        for py in range(y-4,y+h+5):
            for px in range(x-4,x+w+4):
                if px<x or px>=x+w or py<y or py>=y+h:
                    ground.putpixel((px,py),tile.getpixel((min(w-1,max(0,px-x)),min(h-1,max(0,py-y)))))
    ground.save(OUT / "ground.png")
    (OUT / "provenance.json").write_text(json.dumps({"method":"Existing native surface crops softened into owned village materials; street floor paint filtered with unchanged UV layout", "surface_source_sha256":hashlib.sha256(SOURCE.read_bytes()).hexdigest(),"ground_source_sha256":hashlib.sha256(ground_source.read_bytes()).hexdigest(),"recipes":recipes},indent=2)+"\n")
    assert atlas.size == (512,384)
    print("Prepared 12 village material patches and 214 filtered terrain tiles; originals unchanged")


if __name__ == "__main__":
    main()
