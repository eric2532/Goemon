"""Rectify original Kili surface paint for solid village scenery."""
import argparse,hashlib,json,sys
from pathlib import Path
from PIL import Image,ImageStat
from build_village_building_surfaces import surface_atlas
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/maps/falan'
PATCHES={
 'plaster':(11290,[(116,270),(122,274),(122,281),(116,277)],False,(64,64)),
 'roof':(11294,[(153,146),(191,172),(224,149),(184,126)],False,(96,64)),
 'trim':(11290,[(30,169),(35,172),(35,176),(30,173)],False,(64,64)),
 'stone':(11295,[(115,286),(154,260),(154,280),(115,306)],False,(96,64)),
 'timber':(11290,[(242,245),(247,241),(247,257),(242,261)],False,(48,96)),
 'canopy':(11290,[(94,132),(115,143),(133,130),(111,117)],False,(96,64)),
 'awning':(11295,[(205,171),(208,171),(208,174),(205,174)],False,(64,64)),
 'white':(11293,[(185,318),(191,314),(191,324),(185,328)],False,(64,64)),
 'table':(11292,[(85,136),(107,151),(134,132),(113,117)],False,(96,64)),
 'pottery':(11292,[(154,98),(163,102),(163,115),(154,111)],False,(64,64)),
 'pot_green':(11292,[(181,123),(187,125),(187,133),(181,131)],False,(64,64)),
 'leaf':(11190,[(84,50),(89,50),(89,57),(84,57)],False,(64,64)),
 'bell':(11293,[(140,121),(146,125),(146,134),(140,130)],False,(64,64)),
 'medical_red':(11293,[(200,334),(202,334),(202,336),(200,336)],False,(64,64)),
 'wall':(11231,[(22,50),(41,37),(41,80),(22,93)],False,(64,96)),
}

def prepare(source):
 sys.path.insert(0,str(source/'tools'))
 import cg_library as library
 lookup=library.serial_index();images={};hashes={}
 for serial in {v[0] for v in PATCHES.values()}:
  entry=lookup[serial];image=library.image_from_record(entry['pack'],entry['row']);images[serial]=image
  hashes[serial]={'pack':entry['pack'],'row':entry['row'],'rgba_sha256':hashlib.sha256(image.tobytes()).hexdigest()}
 atlas,rows=surface_atlas(images,PATCHES)
 # Average the tiny white-stone crop like the existing plaster recipe, avoiding enlarged palette dithering.
 i=list(PATCHES).index('white');x=i%4*128;y=i//4*128
 patch=atlas.crop((x,y,x+128,y+128));tone=tuple(round(v) for v in ImageStat.Stat(patch).mean[:3])+(255,)
 atlas.paste(Image.blend(patch,Image.new('RGBA',patch.size,tone),.85),(x,y))
 for name in ['wall','leaf']:
  i=list(PATCHES).index(name);region=atlas.crop((i%4*128,i//4*128,i%4*128+128,i//4*128+128))
  assert sum(ImageStat.Stat(region).mean[:3])/3>40, (name,'Source crop is too dark')
 rows[1]='## Generated by tools/recover_kili_surfaces.py; original Kili paint.'
 return atlas,'\n'.join(rows+['}'])+'\n',{'sources':hashes,'patches':PATCHES,'method':'Rectified native building/wall paint; white microtexture is softened using its native average. Existing facade atlas stays intact. Geometry and unseen faces are fitted 3D interpretations.'}

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--source',type=Path,default=ROOT.parent/'Magic Power');parser.add_argument('--check',action='store_true');args=parser.parse_args()
 atlas,data,meta=prepare(args.source.resolve());path=OUT/'kili_surfaces'
 if args.check:
  with Image.open(path.with_suffix('.png')) as actual:assert actual.tobytes()==atlas.tobytes()
  assert path.with_suffix('.gd').read_text()==data
  assert json.loads(path.with_suffix('.json').read_text())==json.loads(json.dumps(meta))
  print('PASS: original Kili surface and feature paint reproduces exactly')
 else:
  atlas.save(path.with_suffix('.png'),optimize=True);path.with_suffix('.gd').write_text(data);path.with_suffix('.json').write_text(json.dumps(meta,indent=2)+'\n')
  print('Recovered',len(PATCHES),'Kili surface and feature patches')
if __name__=='__main__':main()
