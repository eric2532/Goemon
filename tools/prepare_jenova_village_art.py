"""Owned Jenova surface derivatives and reachable scope; preserve original art/map bytes."""
import base64
import hashlib
import json
import re
import struct
import zlib
from collections import deque
from pathlib import Path
from PIL import Image, ImageFilter, ImageOps, ImageStat
ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'assets/maps/original_crossgate'
OUT=ROOT/'assets/maps/falan/jenova/street_art'

def prepare():
    OUT.mkdir(parents=True,exist_ok=True)
    catalog=json.loads((ART/'catalog.json').read_text())
    source=Image.open(ART/'building-surfaces.png').convert('RGB')
    table=(ART/'building-surfaces.gd').read_text()
    recipes={'plaster':'plaster','wood':'woodwall','trim':'jenova_trim','stone':'stone','orange':'orange_roof','green':'green_roof','glass':'jenova_round_window','teal':'jenova_round_door','shutter':'jenova_trim','sign':'jenova_11405_sign','banner':'jenova_11405_banner','carving':'11314_left'}
    atlas=Image.new('RGB',(512,384));lines=['extends RefCounted','## Generated by tools/prepare_jenova_village_art.py.','const TILES={']
    for i,(name,original) in enumerate(recipes.items()):
        if name=='carving':
            g=catalog['graphics']['11314'];x,y,w,h=g['rect']
            original=Image.open(ART/catalog['pages'][g['page']]).crop((x,y,x+w,y+h)).convert('RGB')
            tile=original.transform((112,112),Image.Transform.QUAD,(10,83,10,190,44,210,44,103),Image.Resampling.BICUBIC)
        else:
            x,y=map(int,re.search('"'+original+r'":Vector2\((\d+),(\d+)\)',table).groups())
            tile=source.crop((x+8,y+8,x+120,y+120))
        if name not in ['sign','banner']:
            tile=ImageOps.grayscale(tile.filter(ImageFilter.GaussianBlur(1.3)))
            mean=ImageStat.Stat(tile).mean[0]
            tile=tile.point(lambda p:max(125,min(245,int(207+(p-mean)*.32)))).convert('RGB')
        patch=tile.resize((128,128),Image.Resampling.BICUBIC);patch.paste(tile,(8,8))
        for py in range(128):
            for px in range(128):
                if px<8 or py<8 or px>=120 or py>=120:patch.putpixel((px,py),tile.getpixel((min(111,max(0,px-8)),min(111,max(0,py-8)))))
        atlas.paste(patch,(i%4*128,i//4*128));lines.append(f' "{name}":Vector2({i%4*128},{i//4*128}),')
    atlas.save(OUT/'materials.png');(OUT/'materials.gd').write_text('\n'.join(lines+['}'])+'\n')
    row=catalog['maps']['BlueCrossgate/map/0/4000.dat'];raw=zlib.decompress(base64.b64decode(row['restored_raw']));bits=zlib.decompress(base64.b64decode(row['walk']));w,h=row['size']
    def walk(c):
        x,y=c;i=y*w+x
        return 0<=x<w and 0<=y<h and bits[i>>3]&(1<<(i&7))
    reach={(46,29)};queue=deque(reach)
    while queue:
        x,y=queue.popleft()
        for c in [(x-1,y),(x+1,y),(x,y-1),(x,y+1)]:
            if c not in reach and walk(c):reach.add(c);queue.append(c)
    floor_serials={struct.unpack_from('<H',raw,20+(y*w+x)*2)[0] for x,y in reach}
    records={};pages={};ground=Image.new('RGBA',(16*72,((len(floor_serials)+15)//16)*56))
    masks=Image.new('RGB',ground.size)
    for index,s in enumerate(sorted(floor_serials)):
        g=catalog['graphics'][str(s)];a,b,c,d=g['rect'];assert(c,d)==(64,47)
        if g['page'] not in pages:pages[g['page']]=Image.open(ART/catalog['pages'][g['page']]).convert('RGBA')
        original=pages[g['page']].crop((a,b,a+c,b+d));assert hashlib.sha256(original.tobytes()).hexdigest()==g['rgba_sha256']
        tile=original.copy();pixels=tile.load()
        for y in range(d):
            occupied=[x for x in range(c) if pixels[x,y][3]>127]
            if occupied:
                for x in range(c):pixels[x,y]=pixels[min(max(x,occupied[0]),occupied[-1]),y][:3]+(255,)
        for y in range(d):
            if pixels[32,y][3]==0:
                closest=min((r for r in range(d) if pixels[32,r][3]),key=lambda r:abs(r-y));tile.paste(tile.crop((0,closest,c,closest+1)),(0,y))
        # Native pixels remain at the scope boundary; the original road silhouette
        # becomes a soft mask for one continuous world-space painted treatment.
        mask=Image.new('RGB',tile.size);soft=tile.convert('RGB').filter(ImageFilter.GaussianBlur(1.2))
        for y in range(d):
            for x in range(c):
                r,green,b=soft.getpixel((x,y))
                road=max(0,min(255,round((b/max(1,(r+green)*.5)-.69)/.12*255))) if 3940<=s<=3965 else 0
                dirt=max(0,min(255,round((r-green)/max(1,r)*1000)))
                mask.putpixel((x,y),(road,dirt,0))
        # Calm enlarged palette speckles; keep the separately derived native road mask.
        tile=tile.filter(ImageFilter.GaussianBlur(.65))
        px,py=index%16*72+4,index//16*56+4
        for y in range(-4,d+5):
            for x in range(-4,c+4):
                at=(min(c-1,max(0,x)),min(d-1,max(0,y)))
                ground.putpixel((px+x,py+y),tile.getpixel(at));masks.putpixel((px+x,py+y),mask.getpixel(at))
        records[str(s)]={'rect':[px,py,c,d],'source_rgba_sha256':g['rgba_sha256']}
    ground.save(OUT/'ground.png');masks.save(OUT/'ground-masks.png')
    scope=Image.new('L',(100,100))
    for x,y in reach:scope.putpixel((x,y),255)
    scope=scope.filter(ImageFilter.MinFilter(5)).filter(ImageFilter.GaussianBlur(1.4))
    scope.save(OUT/'ground-scope.png')
    data={'map_sha256':hashlib.sha256(raw).hexdigest(),'reachable_cells':sorted(y*w+x for x,y in reach),'graphics':records,'recipes':recipes,'surface_sha256':hashlib.sha256((ART/'building-surfaces.png').read_bytes()).hexdigest()}
    (OUT/'provenance.json').write_text(json.dumps(data,indent=2)+'\n')
    assert len(reach)>1000
    print(f'Jenova: {len(reach)} reachable cells, {len(records)} floor patches, {len(recipes)} owned material patches')
if __name__=='__main__':prepare()
