"""Rectify original Falan notices and planter brickwork for solid street props."""
import argparse
import hashlib
import json
import sys
from pathlib import Path

from PIL import Image
from build_village_building_surfaces import surface_atlas

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets/maps/falan"
PATCHES = {
    "notice_10413": (10413, [(0,14),(29,31),(29,49),(0,32)], True, (112,65)),
    "notice_10415": (10415, [(7,14),(31,29),(31,62),(7,48)], True, (70,110)),
    "notice_10416": (10416, [(8,31),(32,16),(32,48),(8,63)], True, (70,110)),
    "notice_11496": (11496, [(0,-10),(64,30),(64,58),(0,18)], True, (112,42)),
    "notice_11497": (11497, [(0,29),(60,-9),(60,18),(0,56)], True, (112,42)),
    "stone": (10426, [(8,44),(20,51),(20,59),(8,52)], False, (44,30)),
}
# Opaque masonry corners exclude the client's checkerboard ground shadow.
PLANTERS = {
    10426: ([(2,57),(22,71),(52,49),(32,35)],26),
    10427: ([(2,45),(22,59),(52,37),(32,23)],14),
    10452: ([(2,48),(33,70),(53,55),(22,33)],26),
    10453: ([(2,36),(33,58),(53,43),(22,21)],14),
}


def recover(source):
    sys.path.insert(0, str(source / "tools"))
    import cg_library as library
    images, provenance = {}, {}
    for serial in [10413,10415,10416,10417,10419,11496,11497,10426,10427,10452,10453]:
        entry = library.serial_index()[serial]
        image = library.image_from_record(entry["pack"], entry["row"])
        images[serial] = image
        provenance[serial] = {"pack": entry["pack"], "row": entry["row"],
                              "rgba_sha256": hashlib.sha256(image.tobytes()).hexdigest()}
    atlas, rows = surface_atlas(images, PATCHES)
    rows[1] = "## Generated by tools/recover_falan_street_details.py; preserved native lettering."
    rows += ["}", "const OVALS={"]
    for serial in [11496,11497]:
        index = list(PATCHES).index(f"notice_{serial}")
        tile = atlas.crop((index%4*128+8,index//4*128+8,index%4*128+120,index//4*128+120))
        left, right = [], []
        for y in range(112):
            xs = [x for x in range(112) if tile.getpixel((x,y))[3] >= 128]
            if len(xs) < 3:
                continue
            left.append((min(xs)/111-.5, .5-y/111))
            right.append((max(xs)/111-.5, .5-y/111))
        outline = left+right[::-1]
        assert len(outline) >= 40, serial
        points = ",".join(f"Vector2({x:.6f},{y:.6f})" for x,y in outline)
        rows.append(f" {serial}:[{points}],")
    rows += ["}", "const PLANTERS={"]
    bodies = Image.new("RGBA", (256,128))
    crowns = Image.new("RGBA", bodies.size)
    for i,(serial,(corners,height)) in enumerate(PLANTERS.items()):
        entry = library.serial_index()[serial]
        image = images[serial]
        bodies.paste(image,(i*64,0))
        leaves = image.copy()
        mask = Image.new("L",image.size)
        mask.putdata([a if g>r*1.03 and g>b*.92 else 0 for r,g,b,a in image.getdata()])
        leaves.putalpha(mask)
        assert leaves.getchannel("A").getbbox(), serial
        crowns.paste(leaves,(i*64,0))
        origin = (-entry["x"],-entry["y"])
        floor = []
        for x,y in corners:
            across = (x-origin[0])*3/32
            along = (y-origin[1])/8
            floor.append(((across-along)*.5,(across+along)*.5))
        points = ",".join(f"Vector2({x:.6f},{z:.6f})" for x,z in floor)
        rows.append(f' {serial}:[Rect2({i*64},0,{image.width},{image.height}),Vector2({origin[0]},{origin[1]}),[{points}],{height*.045:.6f}],')
    return atlas, "\n".join(rows+["}"])+"\n", {"graphics": provenance, "patches": PATCHES,
        "planters":PLANTERS,"foliage_mask":"Native green/cyan pixels; RGB values preserved; no repainted leaves",
        "method": "Rectified native faces on solid 3D props; no translated or repainted lettering."}, bodies, crowns


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT.parent / "Magic Power")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    atlas, data, provenance, bodies, crowns = recover(args.source.resolve())
    prefix = OUT / "city_street_surfaces"
    if args.check:
        with Image.open(prefix.with_suffix(".png")) as actual:
            assert actual.convert("RGBA").tobytes() == atlas.tobytes()
        assert prefix.with_suffix(".gd").read_text() == data
        assert json.loads(prefix.with_suffix(".json").read_text()) == json.loads(json.dumps(provenance))
        for name,image in [("city_planter_art",bodies),("city_planter_leaves",crowns)]:
            with Image.open(OUT/f"{name}.png") as actual:assert actual.convert("RGBA").tobytes()==image.tobytes()
        print("PASS: Falan street paint reproduces from preserved source graphics")
    else:
        atlas.save(prefix.with_suffix(".png"), optimize=True)
        prefix.with_suffix(".gd").write_text(data)
        prefix.with_suffix(".json").write_text(json.dumps(provenance, indent=2)+"\n")
        bodies.save(OUT/"city_planter_art.png",optimize=True)
        crowns.save(OUT/"city_planter_leaves.png",optimize=True)
        print("Recovered five native notice faces and original planter brickwork")


if __name__ == "__main__":
    main()
