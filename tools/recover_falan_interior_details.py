"""Recover original clock dials and interior notice paint for the existing solid furniture."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
from PIL import Image,ImageDraw
from build_village_building_surfaces import surface_atlas
from recover_falan_landmarks import rect
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/maps/falan'
PATCHES={
 'clock_10436':(10436,[(26,29),(44,17),(44,47),(26,59)],True,(64,96)),
 'clock_10495':(10495,[(8,18),(29,32),(29,62),(8,48)],True,(64,96)),
 'inn_notice':(17607,[(9,57),(62,21),(62,64),(9,101)],True,(112,48)),
 'office_notice':(17564,[(2,6),(35,28),(35,64),(2,42)],True,(64,72)),
 'guild_notice':(17608,[(8,57),(61,22),(61,72),(8,106)],True,(112,96)),
 'office_door_crown':(17559,[(5,24),(62,63),(62,85),(5,46)],True,(112,40)),
}

def prepare(source):
 sys.path.insert(0,str(source/'tools'))
 import cg_library as library
 lookup=library.serial_index();images={};hashes={}
 for serial in {p[0] for p in PATCHES.values()}:
  entry=lookup[serial];image=library.image_from_record(entry['pack'],entry['row']);images[serial]=image
  hashes[serial]={'pack':entry['pack'],'row':entry['row'],'rgba_sha256':hashlib.sha256(image.tobytes()).hexdigest()}
 atlas,_=surface_atlas(images,PATCHES)
 rows=['extends RefCounted','## Generated by tools/recover_falan_interior_details.py; original interior paint.','const ATLAS=preload("res://assets/maps/falan/interior_details.png")','const FEATURES={']
 for i,(name,patch) in enumerate(PATCHES.items()):
  x,y,w,h=rect(i,patch[3])
  if name.startswith('clock_'):
   mask=Image.new('L',(w,h));draw=ImageDraw.Draw(mask)
   draw.ellipse((0,0,w-1,w-1),fill=255);draw.rectangle((0,w//2,w-1,h-1),fill=255)
   region=atlas.crop((x,y,x+w,y+h));region.putalpha(mask);atlas.paste(region,(x,y))
  rows.append(f' "{name}":Rect2({x},{y},{w},{h}),')
 rows.append('}')
 return atlas,'\n'.join(rows)+'\n',{'sources':hashes,'patches':PATCHES,'method':'Rectified original dials and notice; arched alpha stencil fits the existing solid clock hood. Cases, boards and door retain their original stations.'}

def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--source',type=Path,default=ROOT.parent/'Magic Power');parser.add_argument('--check',action='store_true');args=parser.parse_args()
 atlas,data,meta=prepare(args.source.resolve());path=OUT/'interior_details'
 if args.check:
  with Image.open(path.with_suffix('.png')) as actual:assert actual.tobytes()==atlas.tobytes()
  assert path.with_suffix('.gd').read_text()==data
  assert json.loads(path.with_suffix('.json').read_text())==json.loads(json.dumps(meta))
  print('PASS: original interior dials, notices and door carving reproduce exactly')
 else:
  atlas.save(path.with_suffix('.png'),optimize=True);path.with_suffix('.gd').write_text(data);path.with_suffix('.json').write_text(json.dumps(meta,indent=2)+'\n')
  print('Recovered native clock dials, interior notices and office door carving')
if __name__=='__main__':main()
