"""Verify the sixty client floors' creature identities against the pinned CGMSV reference."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/maps/original_crossgate'
SOURCE = ROOT / 'build/Other Files/Asset Toolkit/Map Encounters/Source'
NPC = ROOT / 'build/Other Files/Asset Toolkit/Cursed Maze/Source/npc-index.txt'
REF = 'https://github.com/linv2/Crossgate_Docker/blob/dd8690ed3df11e4eb5a038a54079a8f40d8e93b3/gmsv/data/'
NAMES = {101032:'地獄獵犬',101710:'大地翼龍',101002:'羅剎',101600:'血腥之刃',101701:'蜥蜴鬥士',101703:'獵豹蜥蜴',101204:'迷你石像怪',101521:'寶貝炸彈',101120:'幽靈',101430:'兇暴仙人掌'}
BOSSES = ['納帕','德爾麥','瑟貝塔','亞爾法','馬帝亞','凱法','帕布提斯馬']

def prepare(source, npc, archive):
    def rows(name):
        return [line.split('\t') for line in (source/name).read_text(encoding='gb18030').splitlines() if line and not line.startswith('#')]
    bases={r[1]:r for r in rows('enemybase.txt')}
    enemies={r[2]:r for r in rows('enemy.txt')}
    groups={r[2]:r for r in rows('group.txt')}
    catalog=json.loads((archive/'data/crossgate/catalog.json').read_text())['entries']
    def key(ident):
        keys=[r['key'] for r in catalog if r['id']==ident and r['key'].startswith('original:') and 2800<=int(r['key'].split(':')[1])<3000]
        assert len(keys)==1,(ident,keys)
        return keys[0]
    floors={}
    for r in rows('encount.txt'):
        ident=int(r[3])
        if not 24009<=ident<=24067 or (ident-24008)%10==0:continue
        for group in filter(None,r[14:24]):
            for enemy in groups[group][5:15]:
                if enemy in ('','0'):continue
                e=enemies[enemy]
                if int(e[4])==1:continue  # Separate capturable level-one records are not floor patrols.
                sprite=int(bases[e[3]][30])
                floors.setdefault(ident,{})[sprite]=(int(e[4]),int(e[5]))
    patrols=[];levels=[]
    for section in range(6):
        first=24009+section*10;roster=floors[first]
        assert all(floors[first+i]==roster for i in range(9))
        assert set(roster)<=NAMES.keys() and len(roster)==(10 if section==5 else 2)
        patrols.append([[key(i),NAMES[i]] for i in sorted(roster)])
        levels.append(min(r[0] for r in roster.values()))
    guardians=[[[key(int(bases[str(4003+i)][30])),name]] for i,name in enumerate(BOSSES[:5])]
    guardians.append([[key(int(bases[str(4008+i)][30])),name] for i,name in enumerate(BOSSES[5:])])
    events=[r.split('\t') for r in npc.read_bytes().decode('gb18030').splitlines() if '\t' in r]
    seals=[];event_rows=[]
    for section in range(6):
        hits=[r for r in events if len(r)>20 and r[8]==str(24018+section*10)]
        assert len(hits)==1,hits
        r=hits[0];seals.append([int(r[9]),int(r[10])]);event_rows.append(r)
        if section<5:assert key(int(r[20]))==guardians[section][0][0]
    gd='extends RefCounted\n## Generated by tools/recover_cursed_maze_encounters.py; reference identities, not BlueCG server combat logic.\n'
    for name,value in [('PATROLS',patrols),('GUARDIANS',guardians),('LEVELS',levels)]:gd+='const '+name+'='+json.dumps(value,ensure_ascii=False)+'\n'
    gd+='const SEALS=['+','.join('Vector2i(%d,%d)'%tuple(p) for p in seals)+']\n'
    proof=dict(reference=REF,source_hashes={f:hashlib.sha256((source/f).read_bytes()).hexdigest() for f in ('encount.txt','group.txt','enemy.txt','enemybase.txt')},npc_index_sha256=hashlib.sha256(npc.read_bytes()).hexdigest(),guardian_events=event_rows,patrols=patrols,guardians=guardians,levels=levels,seals=seals,limits='Client map bytes/art are original. Encounter identity/levels/guardian coordinates use this pinned CGMSV reference, not verified BlueCG server data. Real-time posts, retinues and combat balance are adaptations.')
    return gd,proof

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,default=SOURCE);p.add_argument('--npc',type=Path,default=NPC);p.add_argument('--archive',type=Path,default=ROOT.parent/'Magic Power');p.add_argument('--check',action='store_true');a=p.parse_args()
    gd,proof=prepare(a.source,a.npc,a.archive)
    if a.check:
        assert (OUT/'maze_encounters.gd').read_text()==gd
        assert json.loads((OUT/'maze-encounters.json').read_text())==proof
    else:
        (OUT/'maze_encounters.gd').write_text(gd)
        (OUT/'maze-encounters.json').write_text(json.dumps(proof,ensure_ascii=False,indent=2)+'\n')
    print('CURSED_ENCOUNTER_SOURCE 54 patrol floors / 10 species / 7 named guardians / 6 source seal positions verified')

if __name__=='__main__':main()
