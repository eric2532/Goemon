"""Recover the fixed original rooms on the playable Sokia-to-Falken route."""
import argparse, base64, hashlib, json, math, sys, zlib
from pathlib import Path
from PIL import Image, ImageOps
from build_falan_room_art import project_tile, project_wall
from build_freyja_outlying import is_water

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/maps/falan/falken'
MAPS = (3300, 3301, 23000, 23001, 23002, 23003)
PANELS = (17360,17362,17364,17366)
PILLARS = (17361,17363,17365,17367,17368,17369)


def prepare(source):
    sys.path.insert(0, str(source / 'tools'))
    import cg_library as lib
    from prepare_field_assets import navigation_grid
    lookup = lib.serial_index()
    maps, sources, art = {}, {}, {}
    def graphic(serial):
        if serial not in art:
            e = lookup[serial]
            art[serial] = lib.image_from_record(e['pack'], e['row'])
            sources[serial] = dict(pack=e['pack'], row=e['row'], rgba_sha256=hashlib.sha256(art[serial].tobytes()).hexdigest())
        return art[serial]
    for ident in MAPS:
        path = f'BlueCrossgate/map/0/{ident}.dat'
        with lib.connection() as db:
            key = db.execute('SELECT id FROM files WHERE path=?', (path,)).fetchone()[0]
        raw = lib.source_file(key)[1].read_bytes()
        w, h, floor, objects, _ = lib.parse_map(raw)
        walk = navigation_grid(w, h, floor, objects, lookup)
        maps[ident] = dict(size=(w,h), floor=floor, objects=objects, walk=walk, source=path, sha256=hashlib.sha256(raw).hexdigest())
    floor_ids = sorted({3256, *[s for m in maps.values() for s in m['floor'] if s and s in lookup]})
    is_wall = lambda s: 13000 <= s < 14000 or 15800 <= s < 16000 or 16900 <= s < 17000 or 17360 <= s <= 17369 or s == 17644
    wall_ids = sorted({15827, *[s for m in maps.values() for s in m['objects'] if s in lookup and is_wall(s)]})
    floors = Image.new('RGB', (32*36, math.ceil((len(floor_ids)+1)/32)*36))
    walls = Image.new('RGBA', (16*36, math.ceil((len(wall_ids)+1)*2/16)*100))
    for i, serial in enumerate(floor_ids,1):floors.paste(project_tile(graphic(serial)), ((i-1)%32*36,(i-1)//32*36))
    wall_relief, wall_caps, mirrored_faces, invisible = {}, [], [], []
    for i, serial in enumerate(wall_ids):
        im = graphic(serial)
        bounds = im.getchannel('A').getbbox()
        if bounds is None:invisible.append(i+1)
        top = bounds[1] if bounds else 0
        pixels = [im.getpixel((x,y)) for y in range(top,min(top+8,im.height)) for x in range(im.width) if im.getpixel((x,y))[3] == 255] or [(0,0,0)]
        wall_caps.append(tuple(sorted(p[c] for p in pixels)[len(pixels)//2] for c in range(3)))
        faces = [project_wall(im,lookup[serial],bool(side)) for side in range(2)]
        missing = [sum(p[:3] == (127,115,94) for p in f.getdata()) for f in faces]
        if max(missing)>1800 and min(missing)==0:
            # These sprites contain one face, not a full two-face wall. Reuse its native reverse.
            good = missing.index(min(missing))
            faces[1-good] = ImageOps.mirror(faces[good])
            mirrored_faces.append(serial)
        for side, face in enumerate(faces):
            walls.paste(face, ((i*2+side)%16*36,(i*2+side)//16*100))
            # Shallow source-guided relief; original texture, anchors and wall footprint stay authoritative.
            samples = face.crop((2,2,34,98)).convert('L').resize((5,25),Image.Resampling.BOX)
            wall_relief[i*2+side] = [round(p/255,4) for p in samples.getdata()]
    floor_slots = {s:i for i,s in enumerate(floor_ids,1)}
    wall_slots = {s:i for i,s in enumerate(wall_ids,1)}
    placed, used = {}, {14526,14193,14195,14197,12000,12002}
    for ident, m in maps.items():
        w,h = m['size'];rows=[]
        for i,s in enumerate(m['objects']):
            if s < 1000 or s not in lookup or (s in wall_slots and s not in PILLARS):continue
            e=lookup[s];rows.append((i%w,i//w,s,max(1,e['east']),max(1,e['south'])))
            used.add(s)
        placed[ident]=rows
    atlas = Image.new('RGBA',(2048,4096));rects={};x=y=row_h=0
    for serial in sorted(used):
        im=graphic(serial)
        if x+im.width+4>2048:x=0;y+=row_h;row_h=0
        assert y+im.height+4 <= 4096, serial
        atlas.alpha_composite(im,(x+2,y+2));rects[serial]=(x+2,y+2,im.width,im.height)
        x+=im.width+4;row_h=max(row_h,im.height+4)
    atlas=atlas.crop((0,0,2048,y+row_h))
    rows=['extends RefCounted','## Generated by tools/recover_falken_route.py; source maps remain authoritative.','const ROOMS={']
    for ident,m in maps.items():
        w,h=m['size'];bits=bytearray((w*h+7)//8)
        for i,opened in enumerate(m['walk']):
            if opened:bits[i>>3] |= 1<<(i&7)
        assert any(bits), ident
        rows.append(f' {ident}:[Vector2i({w},{h}),Vector2({-w*1.5},{-h*1.5}),"{bits.hex()}"],')
    rows+=['}',f'const TOWER_FLOOR={floor_slots[3256]}',f'const TOWER_WALL={wall_slots[15827]}']
    with lib.connection() as db:key=db.execute("SELECT id FROM files WHERE path='BlueCrossgate/map/0/300.dat'").fetchone()[0]
    raw=lib.source_file(key)[1].read_bytes();w,h,f,o,_=lib.parse_map(raw)
    desert_hash=hashlib.sha256(raw).hexdigest()
    walk=navigation_grid(w,h,f,o,lookup)
    start=(402,304);goal=(540,350);queue=[start];previous={start:None}
    for x,z in queue:
        if (x,z)==goal:break
        for p in [(x+1,z),(x,z+1),(x,z-1),(x-1,z)]:
            a,b=p
            if p in previous or not (370<=a<=578 and 166<=b<=374):continue
            if not walk[b*w+a] or is_water(f[b*w+a]):continue
            previous[p]=(x,z);queue.append(p)
    assert goal in previous, 'Falken trail must connect to Great Wind on the original map'
    trail=[];p=goal
    while p is not None:trail.append(p);p=previous[p]
    trail.reverse();signs=trail[::24]
    rows+=['const DESERT_TRAIL=['+','.join(f'Vector2({x*3},{z*3})' for x,z in signs)+']']
    for field, slots, key in [('FLOORS',floor_slots,'floor'),('WALLS',wall_slots,'objects')]:
        rows+=['const '+field+'={']
        for ident,m in maps.items():
            raw=b''.join(slots.get(s,0).to_bytes(2,'little') for s in m[key])
            rows.append(f' {ident}:"{base64.b64encode(zlib.compress(raw)).decode()}",')
        rows+=['}']
    rows+=['const WALL_HEIGHTS='+str([lookup[17360 if s in PANELS else s]['h'] for s in wall_ids]),
           'const WALL_PILLARS='+str([wall_slots[s] for s in PILLARS if s in wall_slots]),
           'const WALL_INVISIBLE='+str(invisible),
           'const WALL_RELIEF_SIZE=Vector2i(4,24)',
           'const WALL_RELIEF='+str(wall_relief),
           'const WALL_CAPS=['+','.join(f'Color8({r},{g},{b})' for r,g,b in wall_caps)+']',
           'const GRAPHICS={']
    rows += [f' {s}:Rect2i({",".join(map(str,r))}),' for s,r in rects.items()]
    rows+=['}','const PROPS={']
    for ident,props in placed.items():
        rows.append(f' {ident}:['+','.join(f'[Vector2i({x},{z}),{s},Vector2i({a},{b})]' for x,z,s,a,b in props)+'],')
    rows+=['}']
    rows+=['const ORIGINS={'+','.join(f'{s}:Vector2({-lookup[s]["x"]},{-lookup[s]["y"]})' for s in used)+'}']
    patches={12000:(10,48),12002:(47,20)}
    for s,(x,y) in patches.items():assert all(graphic(s).getpixel((a,b))[3]==255 for b in range(y,y+8) for a in range(x,x+8))
    rows+=['const STAIR_PATCHES={'+','.join(f'{s}:Rect2i({rects[s][0]+x},{rects[s][1]+y},8,8)' for s,(x,y) in patches.items())+'}']
    meta=dict(maps={i:dict(source=m['source'],sha256=m['sha256'],size=m['size'],props=len(placed[i])) for i,m in maps.items()},sources=sources,desert_trail=trail,desert_map_sha256=desert_hash,
              tower_source=json.loads((ROOT/'assets/references/falken/original.json').read_text()),
              wall_geometry=dict(relief_grid=[4,24],relief='Original projected face luminance, recessed by at most 0.12 inside the wall footprint; fitted depth.',caps='Median opaque RGB in the first eight source rows. Empty original graphics are not rendered.',mirrored_faces=mirrored_faces,panels=list(PANELS),panel_reverse='Mirror the source single face, replacing generic beige padding. Gold panels use the 92-pixel unshadowed panel height.',pillars=list(PILLARS),pillar_geometry='Original anchors and paint on fitted shared column/rail parts, not full wall cubes.'),
              route='Desert ancient people -> ruined village -> temporal room -> ancient capital -> rebel -> tower entrance -> 16 random floors -> Yeka -> Falken -> reward chamber. Maze geometry and unseen 3D remain fitted.',
              reference='https://wiki2.gamer.com.tw/wiki.php?n=3128%3A%E8%A8%8E%E4%BC%90%E6%B3%95%E7%88%BE%E8%82%AF')
    return {'floors.png':floors,'walls.png':walls,'props.png':atlas},'\n'.join(rows)+'\n',meta


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,default=ROOT.parent/'Magic Power');p.add_argument('--check',action='store_true');a=p.parse_args()
    images,data,meta=prepare(a.source.resolve())
    if a.check:
        for name,im in images.items():
            with Image.open(OUT/name) as actual:assert actual.size==im.size and actual.tobytes()==im.tobytes(),name
        assert (OUT/'data.gd').read_text()==data
        assert json.loads((OUT/'provenance.json').read_text())==json.loads(json.dumps(meta))
        print('FALKEN_ROUTE_SOURCE_CHECK six original navigation grids, tower contract, paint and scenery anchors preserved')
    else:
        OUT.mkdir(parents=True,exist_ok=True)
        for name,im in images.items():im.save(OUT/name,optimize=True)
        (OUT/'data.gd').write_text(data)
        (OUT/'provenance.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2)+'\n')
        print('Recovered six fixed original Falken route maps and',len(meta['sources']),'native graphics')


if __name__=='__main__':main()
