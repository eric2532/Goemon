"""Recover Black Prayer's native cave materials and fixed entrance from the source cache."""
import argparse, hashlib, json, math, sys
from pathlib import Path
from PIL import Image, ImageOps
from build_falan_room_art import project_tile, project_wall
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/maps/falan/black_prayer'


def prepare(source):
    sys.path.insert(0, str(source / 'tools'))
    import cg_library as lib
    from prepare_field_assets import navigation_grid
    lookup = lib.serial_index()
    sources = {}
    def graphic(serial):
        entry = lookup[serial]
        image = lib.image_from_record(entry['pack'], entry['row'])
        sources[str(serial)] = dict(pack=entry['pack'], row=entry['row'], rgba_sha256=hashlib.sha256(image.tobytes()).hexdigest())
        return image
    with lib.connection() as db:
        key = db.execute('SELECT id FROM files WHERE path=?', ('BlueCrossgate/map/0/16507.dat',)).fetchone()[0]
    raw = lib.source_file(key)[1].read_bytes()
    w, h, floor, objects, _ = lib.parse_map(raw)
    walk = navigation_grid(w, h, floor, objects, lookup)
    bits = bytearray((w*h+7)//8)
    for i, opened in enumerate(walk):
        if opened: bits[i>>3] |= 1 << (i&7)
    serials = sorted({9555, *floor} - {0})
    atlas = Image.new('RGB', (32*36, math.ceil((len(serials)+1)/32)*36))
    tiles = {serial:i+1 for i,serial in enumerate(serials)}
    for serial, i in tiles.items(): atlas.paste(project_tile(graphic(serial)), ((i-1)%32*36,(i-1)//32*36))
    walls = sorted({s for s in objects if 13000 <= s < 14000 and s != 13268} | set(range(13792,13828)))
    walls = [s for s in walls if s in lookup]
    faces = Image.new('RGBA', (16*36, math.ceil((len(walls)+1)*2/16)*100))
    for i, serial in enumerate(walls,1):
        image = graphic(serial)
        for side in range(2):
            tile=i*2+side
            faces.paste(project_wall(image, lookup[serial], bool(side), cave=True), (tile%16*36,tile//16*100))
    # Opaque native stone from the same faces supplies roof and silhouette joins.
    rock = Image.new('RGB',(256,256))
    for family, serial in enumerate((13792, walls[0],13792,walls[0])):
        face=project_wall(graphic(serial),lookup[serial],True,cave=False)
        patch=face.crop((8,18,26,76)).resize((32,64),Image.Resampling.BICUBIC)
        strip=Image.new('RGB',(64,64));strip.paste(patch,(0,0));strip.paste(ImageOps.mirror(patch),(32,0))
        for variant in range(2):
            rock.paste(strip,(family*64,variant*128));rock.paste(ImageOps.flip(strip),(family*64,variant*128+64))
    palace=project_wall(graphic(15810),lookup[15810],False,cave=False).crop((2,2,34,98))
    assert len(palace.getcolors(10000))>64, 'Native palace masonry must contain real stone detail'
    stair_images={str(s):graphic(s) for s in (17974,17975)}
    # Original small rocks remain the reference for fitted solid 3D scatter.
    for serial in range(15011,15021): graphic(serial)
    native_floor=''.join(tiles.get(s,0).to_bytes(2,'little').hex() for s in floor)
    native_walls=''.join((walls.index(s)+1 if s in walls else 0).to_bytes(2,'little').hex() for s in objects)
    data='extends RefCounted\n## Generated by tools/recover_black_prayer.py; source cache remains authoritative.\n'
    data+=f'const ENTRANCE=[Vector2i({w},{h}),Vector2(-30,-30),"{bits.hex()}"]\n'
    data+=f'const ENTRANCE_FLOOR="{native_floor}"\nconst ENTRANCE_WALLS="{native_walls}"\n'
    data+=f'const GROUND_TILE={tiles[9555]}\nconst MAZE_WALLS={[(walls.index(s)+1) for s in walls if 13792<=s<=13827]}\n'
    meta=dict(map='BlueCrossgate/map/0/16507.dat',map_sha256=hashlib.sha256(raw).hexdigest(),sources=sources,
              configuration='https://github.com/linv2/Crossgate_Docker/blob/dd8690ed3df11e4eb5a038a54079a8f40d8e93b3/gmsv/data/dungeonconf.txt',
              sample='BlueCrossgate/map/1/3/80.dat',floor_serials=serials,wall_serials=walls)
    return {'floors.png':atlas,'walls.png':faces,'rock.png':rock,'palace_wall.png':palace,**{f'stair_{s}.png':im for s,im in stair_images.items()}},data,meta


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,default=ROOT.parent/'Magic Power');p.add_argument('--check',action='store_true');a=p.parse_args()
    images,data,meta=prepare(a.source.resolve())
    if a.check:
        for name,im in images.items():
            with Image.open(OUT/name) as actual: assert actual.mode==im.mode and actual.size==im.size and actual.tobytes()==im.tobytes(), name
        assert (OUT/'data.gd').read_text()==data
        assert json.loads((OUT/'provenance.json').read_text())==meta
        print('BLACK_PRAYER_RECOVERY_CHECK original pixels, map navigation and provenance preserved')
    else:
        OUT.mkdir(parents=True,exist_ok=True)
        for name,im in images.items():im.save(OUT/name,optimize=True)
        (OUT/'data.gd').write_text(data)
        (OUT/'provenance.json').write_text(json.dumps(meta,ensure_ascii=False,indent=2)+'\n')
        print('Recovered',len(meta['sources']),'original graphics and map 16507')
if __name__=='__main__':main()
