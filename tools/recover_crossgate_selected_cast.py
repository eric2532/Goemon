"""Recover Pete, Grace, Rei and Cedi through the shared Cross Gate atlas contract."""
import argparse
import hashlib
import json
import sys
from pathlib import Path
from PIL import Image

from recover_crossgate_kazi import ROOT, pack_frames
from recover_crossgate_shin import prepare_stance

CAST = {
    'pete': (44, 106025, (106025,)),
    'grace': (45, 106375, (106375, 106234)),
    'rei': (46, 105350, (105350, 100350)),
    'cedi': (47, 106000, (106000,)),
}
REPORT = ROOT / 'build/Other Files/Asset Toolkit/Pete Grace Rei Cedi'


def recover(source):
    sys.path.insert(0, str(source / 'tools'))
    import cg_assets as cg
    import cg_sounds
    skins = {s['id']: s for s in json.loads((source / 'godot/assets/exploration/skins.json').read_text())['skins']}
    families = json.loads((source / 'data/crossgate/character-families.json').read_text())['families']
    existing_audio = {}
    for path in (ROOT / 'assets/audio/crossgate').rglob('*.wav'):
        existing_audio.setdefault(path.name.lower(), []).append(path)
    definitions = ['extends RefCounted', '## Generated by recover_crossgate_selected_cast.py; preserve source IDs.']
    report = {}
    routes_path = ROOT / 'assets/ui/portraits/crossgate/skins.json'
    heads = json.loads(routes_path.read_text())
    for name, (character, default, anchors) in CAST.items():
        ids = {i for family in families if any(a in family['appearances'] for a in anchors)
               for i in family['appearances']}
        catalog = []
        report[name] = []
        for skin in [default] + sorted(ids - {default}):
            member = next((m for m in skins[skin]['members'] if m['label'] == '空手'), None)
            if skin == 106234:
                member = next(m for m in skins[skin]['members'] if m['id'] == 106236)
            if member is None:
                assert skin == 111619, (name, skin)
                member = skins[skin]['members'][0]
            weapon = 'unarmed'
            key = member['key']
            folder = ROOT / f'assets/characters/crossgate/fighters/{name}/{skin}'
            folder.mkdir(parents=True, exist_ok=True)
            unique = {}
            stance, portrait_clip = prepare_stance(cg, weapon, key, member['id'], unique,
                                                   (0, 1, 3, 5, 6, 8, 9, 10))
            audio = {}
            for clip in cg.actor(key)[2]:
                if clip['action'] != 5:
                    continue
                saved = stance['clips'][f'5:{clip["direction"]}']
                cues = cg_sounds.clip_cues(clip)
                hits = [c for c in cues if c['flag'] >= 10000]
                swings = [c for c in cues if c['flag'] < 10000]
                assert hits, (skin, clip['direction'])
                saved.update(duration=clip['duration']/1000, contacts=[c['atMs']/1000 for c in hits],
                             contact_cues=[c['id'] for c in hits], sounds=swings)
                for cue in cues:
                    filename = Path(cue['file']).name
                    raw = (cg.SOURCE / 'se' / filename).read_bytes()
                    digest = hashlib.sha256(raw).hexdigest()
                    found = next((p for p in existing_audio.get(filename.lower(), [])
                                  if hashlib.sha256(p.read_bytes()).hexdigest() == digest), None)
                    if found is None:
                        found = ROOT / 'assets/audio/crossgate/selected_cast' / filename
                        found.parent.mkdir(parents=True, exist_ok=True)
                        found.write_bytes(raw)
                        existing_audio.setdefault(filename.lower(), []).append(found)
                    audio[str(cue['id'])] = 'res://' + str(found.relative_to(ROOT))
            pages = pack_frames(stance['clips'], unique, folder)
            im, x, y = cg.frame_parts(key, portrait_clip, 0)
            box = im.getbbox()
            portrait = im.crop(box)
            portrait.save(folder / 'portrait.png')
            origin = [x+box[0], y+box[1]]
            body_pixels = portrait.height - 7
            manifest = dict(stance, id=skin, pages=pages, portrait_origin=origin,
                            body_pixels=body_pixels, audio=audio)
            (folder / 'motions.json').write_text(json.dumps(manifest, separators=(',', ':'))+'\n')
            label = ('Original' if skin == default else 'Alternative') + f' · {skin}'
            if skin == 111619:
                label = 'Special · Gold / Purple Effect'
            catalog.append(f'\t{skin}:[{json.dumps(label)},Vector2({origin[0]},{origin[1]}),{body_pixels}],')
            # Preserve the recovered head's exact pixels and selected palette.
            head = portrait.crop((0, 0, portrait.width, min(portrait.height, max(30, body_pixels//2))))
            canvas = Image.new('RGBA', (256, 256))
            factor = min(236/head.width, 236/head.height)
            head = head.resize((round(head.width*factor), round(head.height*factor)), Image.Resampling.NEAREST)
            canvas.paste(head, ((256-head.width)//2, (256-head.height)//2))
            head_path = ROOT / f'assets/ui/portraits/crossgate/recovered/{name}-{skin}.png'
            head_path.parent.mkdir(exist_ok=True)
            canvas.save(head_path)
            heads[f'{character}:{skin}'] = f'recovered/{name}-{skin}.png'
            # Atlas storage must retain every prepared source pixel and origin.
            atlases = [Image.open(folder/f'atlas-{i}.png').convert('RGBA') for i in range(pages)]
            checked = 0
            for pose, motion in stance['clips'].items():
                clip = cg.actor(key)[2][motion['source_clip']]
                assert len(clip['frames']) == len(motion['frames'])
                for index, region in enumerate(motion['frames']):
                    im, x, y = cg.frame_parts(key, clip['index'], index)
                    box = im.getbbox()
                    page, left, top, width, height, ox, oy = region
                    assert atlases[page].crop((left,top,left+width,top+height)).tobytes() == im.crop(box).tobytes()
                    assert (ox,oy) == (x+box[0],y+box[1])
                    checked += 1
            report[name].append(dict(skin=skin, source_id=member['id'], key=key, pages=pages,
                                     frames_checked=checked, body_pixels=body_pixels))
            print(f'{name} {skin}: {checked} exact frames/origins, {pages} pages', flush=True)
        definitions.append(f'const {name.upper()}={{\n'+'\n'.join(catalog)+'\n}')
    assert sum(map(len, report.values())) == 53
    assert 106234 in {s['skin'] for s in report['grace']}
    (ROOT / 'scripts/crossgate_cast_skins.gd').write_text('\n\n'.join(definitions)+'\n')
    routes_path.write_text(json.dumps(heads, ensure_ascii=False, indent=2)+'\n')
    REPORT.mkdir(parents=True, exist_ok=True)
    (REPORT / 'recovery.json').write_text(json.dumps(report, indent=2)+'\n')
    for path in list((ROOT/'assets/characters/crossgate/fighters').glob('*/*/atlas-*.png')) + list((ROOT/'assets/ui/portraits/crossgate/recovered').glob('*.png')):
        if path.with_suffix('.png.import').exists():
            continue
        path.with_suffix('.png.import').write_text('[remap]\nimporter="texture"\ntype="CompressedTexture2D"\n[deps]\nsource_file="res://'+str(path.relative_to(ROOT))+'"\n[params]\ncompress/mode=0\nprocess/fix_alpha_border=true\nmipmaps/generate=false\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    recover(parser.parse_args().source.resolve())
