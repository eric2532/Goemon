def source_coverage(width,height,ground,objects,walk,regions,flags):
 # Inspect every source component, including ground unreachable from today's gates.
 covered=bytearray(width*height)
 for region in regions.values():
  x,y,w,h=region['bounds']
  for z in range(max(0,y),min(height,y+h)):
   for a in range(max(0,x),min(width,x+w)):covered[z*width+a]=1
 outside=[i for i,value in enumerate(ground) if value and not covered[i]]
 missing_land=[i for i in outside if not is_water(ground[i])]
 missing_objects=[i for i,value in enumerate(objects) if value and not covered[i]]
 missing_walk=[i for i,value in enumerate(walk) if value and not covered[i]]
 missing_ports=[i for i,value in enumerate(flags) if value&2 and not covered[i]]
 seen=bytearray(width*height);components=[]
 for seed,opened in enumerate(walk):
  if not opened or seen[seed]:continue
  pending=[seed];seen[seed]=1;count=0;uncovered=0;low=[width,height];high=[0,0]
  while pending:
   i=pending.pop();x,y=i%width,i//width;count+=1;uncovered+=not covered[i]
   low=[min(low[0],x),min(low[1],y)];high=[max(high[0],x),max(high[1],y)]
   for neighbor in (i-1 if x else -1,i+1 if x+1<width else -1,i-width,i+width):
    if 0<=neighbor<width*height and walk[neighbor] and not seen[neighbor]:
     seen[neighbor]=1;pending.append(neighbor)
  components.append(dict(seed=[seed%width,seed//width],cells=count,bounds=[*low,*high],outside_crops=uncovered))
 assert not missing_land,('Original land outside Sokia crops',[(i%width,i//width) for i in missing_land[:10]])
 assert not missing_objects,('Original objects outside Sokia crops',[(i%width,i//width) for i in missing_objects[:10]])
 assert not missing_walk,('Original open cells outside Sokia crops',[(i%width,i//width) for i in missing_walk[:10]])
 assert not missing_ports,('Original flagged entrances outside Sokia crops',[(i%width,i//width) for i in missing_ports[:10]])
 return dict(nonzero_ground_cells=sum(bool(v) for v in ground),object_cells=sum(bool(v) for v in objects),
             decoder_open_cells=sum(bool(v) for v in walk),components=components,
             flagged_entrances=sum(bool(v&2) for v in flags),outside_crops=dict(nonzero_ground_cells=len(outside),
             ground_serials=dict(Counter(ground[i] for i in outside)),nonwater_ground_cells=0,object_cells=0,decoder_open_cells=0,flagged_entrances=0),
             water_owner='forest_freyja_art.gd uses scenery/water.png and full source bounds in every Sokia crop',
             limits='Four-neighbour decoder geometry and source-mask coverage only; original server collision, event access and rendered visual fidelity require separate checks.')

def rectangles(cells):
 remaining=set(cells);result=[]
 while remaining:
  x,z=min(remaining,key=lambda p:(p[1],p[0]));w=1
  while (x+w,z) in remaining:w+=1
  h=1
  while all((a,z+h) in remaining for a in range(x,x+w)):h+=1
  remaining.difference_update((a,b) for b in range(z,z+h) for a in range(x,x+w))
  result.append((x,z,w,h))
 return result

def prepare(source):
 sys.path.insert(0,str(source/'tools'))
 import cg_library as lib
 from prepare_field_assets import navigation_grid
 lookup=lib.serial_index();w,h,ground,objects,flags=load_map(lib,300)
 walk=navigation_grid(w,h,ground,objects,lookup)
 rows=['extends RefCounted','## Generated by tools/recover_sokia.py; original map 300 coordinates.','const SCENERY={']
 masks={};blocks={};counts={};used=set()
 for area,radius in AREAS.items():
  _,(ox,oz),_=REGIONS[area];left,top=ox-radius,oz-radius;size=2*radius+1
  image=Image.new('RGBA',(size,size));placed=[];blocked=set()
  for z in range(top,top+size):
   for x in range(left,left+size):
    inside=0<=x<w and 0<=z<h
    tile=ground[z*w+x] if inside else 0;serial=objects[z*w+x] if inside else 0
    wet=not tile or is_water(tile)
    pave=255 if area=='ghana_north_road' and tile==100 and serial==2 else 220 if 6777<=tile<=6798 else 0
    image.putpixel((x-left,z-top),(255 if wet else 0,224 if not wet and is_road(tile) else 0,pave,255))
    if not wet and not walk[z*w+x]:blocked.add((x,z))
    if serial<1000 or serial not in lookup:continue
    e=lookup[serial];span=(max(1,e['east']),max(1,e['south']))
    placed.append((x,z,serial,*span,e['h']))
    if not (12500<=serial<=12565 or 10058<=serial<=10074 or 10085<=serial<=10094 or 11188<=serial<=11208 or 11230<=serial<=11265 or serial==11297):used.add(serial)
  masks[area]=image;blocks[area]=rectangles(blocked)
  assert {(x,z) for a,b,rw,rh in blocks[area] for x in range(a,a+rw) for z in range(b,b+rh)}==blocked
  assert sum(rw*rh for a,b,rw,rh in blocks[area])==len(blocked)
  counts[area]={'bounds':[left,top,size,size],'placements':len(placed),'blocked_cells':len(blocked),'collision_rectangles':len(blocks[area]),'serials':dict(Counter(p[2] for p in placed))}
  rows.append(' "'+area+'":[')
  rows.extend(f'  [Vector2i({x},{z}),{s},Vector2i({ew},{ns}),{height},false],' for x,z,s,ew,ns,height in placed)
  rows.append(' ],')
 rows+=['}','const BLOCKS={']
 for area,rects in blocks.items():rows.append(' "'+area+'":['+','.join('Rect2i(%d,%d,%d,%d)'%r for r in rects)+'],')
 rows+=['}','const GRAPHICS={']
 old_rects={};old_atlas=None
 if (OUT/'data.gd').exists()and(OUT/'props.png').exists():
  original=(OUT/'data.gd').read_text().split('const GRAPHICS={',1)[1]
  old_rects={int(s):tuple(map(int,(x,y,w,h)))for s,x,y,w,h in re.findall(r'(\d+):Rect2i\((\d+),(\d+),(\d+),(\d+)\)',original)}
  old_atlas=Image.open(OUT/'props.png').convert('RGBA');used.update(old_rects)
 images=[];x=0;y=old_atlas.height if old_atlas else 0;row_h=0;hashes={}
 for serial in sorted(used):
  e=lookup[serial];im=lib.image_from_record(e['pack'],e['row'])
  assert im.width+4<=2048
  if serial in old_rects:
   rect=old_rects[serial];assert rect[2:]==im.size
   expected=Image.new('RGBA',im.size);expected.alpha_composite(im)
   assert old_atlas.crop((rect[0],rect[1],rect[0]+rect[2],rect[1]+rect[3])).tobytes()==expected.tobytes()
  else:
   if x+im.width+4>2048:x=0;y+=row_h;row_h=0
   rect=(x+2,y+2,im.width,im.height);images.append((im,rect[:2]))
   x+=im.width+4;row_h=max(row_h,im.height+4)
  hashes[str(serial)]={'pack':e['pack'],'row':e['row'],'rgba_sha256':hashlib.sha256(im.tobytes()).hexdigest()}
  if serial in [10017,11139,11229,11294,11366,12199,16794]:
   b=im.getbbox();hashes[str(serial)]['native_visible_bounds']=[e['x']+b[0],e['y']+b[1],b[2]-b[0],b[3]-b[1]]
  rows.append(f' {serial}:Rect2i({rect[0]},{rect[1]},{rect[2]},{rect[3]}),')
 atlas=Image.new('RGBA',(2048,y+row_h))
 if old_atlas:atlas.paste(old_atlas,(0,0))
 for im,at in images:atlas.alpha_composite(im,at)
 rows+=['}','const MASK_RGBA='+json.dumps({area:hashlib.sha256(image.tobytes()).hexdigest()for area,image in masks.items()},sort_keys=True)]
 meta={'map':300,'map_size':[w,h],'ground_sha256':hashlib.sha256(bytes().join(int(v).to_bytes(2,'little') for v in ground)).hexdigest(),'object_sha256':hashlib.sha256(bytes().join(int(v).to_bytes(2,'little') for v in objects)).hexdigest(),'regions':counts,'source_graphics':hashes,'whole_source_coverage':source_coverage(w,h,ground,objects,walk,counts,flags),'method':'Every archived object anchor retained, original dry blocked-cell union merged without expansion, native ground/water/road masks without traced paint or fading. Compatible trees/cliffs remain 3D; other scenery retains source art.'}
 from prepare_sokia_outdoor_source import source_folder
 folder=source_folder()
 if (folder/'provenance.json').exists():meta['source_completion']=json.loads((folder/'provenance.json').read_text())
 return masks,atlas,'\n'.join(rows)+'\n',meta

