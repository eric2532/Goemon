"""Recover the complete existing Sokia region crops from original map 300."""
import argparse,hashlib,json,sys,tempfile
from collections import Counter
from pathlib import Path
from PIL import Image
from build_freyja_destinations import load_map
from build_freyja_outlying import REGIONS,is_water,is_road
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/maps/falan/sokia'
AREAS={'sokia_coast':120,'sokia_desert':104,'ghana_road':102,'ghana_north_road':82}

def rectangles(cells):
 remaining=set(cells);result=[]
 while remaining:
  x,z=min(remaining,key=lambda p:(p[1],p[0]));w=1
  while (x+w,z) in remaining:w+=1
  h=1
  while all((a,z+h) in remaining for a in range(x,x+w)):h+=1
  remaining.difference_update((a,b) for b in range(z,z+h) for a in range(x,x+w))
  result.append((x,z,w,h))
 return result

def prepare(source):
 sys.path.insert(0,str(source/'tools'))
 import cg_library as lib
 from prepare_field_assets import navigation_grid
 lookup=lib.serial_index();w,h,ground,objects,_=load_map(lib,300)
 walk=navigation_grid(w,h,ground,objects,lookup)
 rows=['extends RefCounted','## Generated by tools/recover_sokia.py; original map 300 coordinates.','const SCENERY={']
 masks={};blocks={};counts={};used=set()
 for area,radius in AREAS.items():
  _,(ox,oz),_=REGIONS[area];left,top=ox-radius,oz-radius;size=2*radius+1
  image=Image.new('RGBA',(size,size));placed=[];blocked=set()
  for z in range(top,top+size):
   for x in range(left,left+size):
    inside=0<=x<w and 0<=z<h
    tile=ground[z*w+x] if inside else 0;serial=objects[z*w+x] if inside else 0
    wet=not tile or is_water(tile)
    pave=255 if area=='ghana_north_road' and tile==100 and serial==2 else 220 if 6777<=tile<=6798 else 0
    image.putpixel((x-left,z-top),(255 if wet else 0,224 if not wet and is_road(tile) else 0,pave,255))
    if not wet and not walk[z*w+x]:blocked.add((x,z))
    if serial<1000 or serial not in lookup:continue
    e=lookup[serial];span=(max(1,e['east']),max(1,e['south']))
    placed.append((x,z,serial,*span,e['h']))
    if not (12500<=serial<=12565 or 10058<=serial<=10074 or 10085<=serial<=10094 or 11188<=serial<=11208 or 11230<=serial<=11265 or serial==11297):used.add(serial)
  masks[area]=image;blocks[area]=rectangles(blocked)
  assert {(x,z) for a,b,rw,rh in blocks[area] for x in range(a,a+rw) for z in range(b,b+rh)}==blocked
  assert sum(rw*rh for a,b,rw,rh in blocks[area])==len(blocked)
  counts[area]={'bounds':[left,top,size,size],'placements':len(placed),'blocked_cells':len(blocked),'collision_rectangles':len(blocks[area]),'serials':dict(Counter(p[2] for p in placed))}
  rows.append(' "'+area+'":[')
  rows.extend(f'  [Vector2i({x},{z}),{s},Vector2i({ew},{ns}),{height},false],' for x,z,s,ew,ns,height in placed)
  rows.append(' ],')
 rows+=['}','const BLOCKS={']
 for area,rects in blocks.items():rows.append(' "'+area+'":['+','.join('Rect2i(%d,%d,%d,%d)'%r for r in rects)+'],')
 rows+=['}','const GRAPHICS={']
 images=[];x=y=row_h=0;hashes={}
 for serial in sorted(used):
  e=lookup[serial];im=lib.image_from_record(e['pack'],e['row'])
  assert im.width+4<=2048
  if x+im.width+4>2048:x=0;y+=row_h;row_h=0
  images.append((im,(x+2,y+2)))
  hashes[str(serial)]={'pack':e['pack'],'row':e['row'],'rgba_sha256':hashlib.sha256(im.tobytes()).hexdigest()}
  rows.append(f' {serial}:Rect2i({x+2},{y+2},{im.width},{im.height}),')
  x+=im.width+4;row_h=max(row_h,im.height+4)
 atlas=Image.new('RGBA',(2048,y+row_h))
 for im,at in images:atlas.alpha_composite(im,at)
 rows+=['}']
 meta={'map':300,'map_size':[w,h],'ground_sha256':hashlib.sha256(bytes().join(int(v).to_bytes(2,'little') for v in ground)).hexdigest(),'object_sha256':hashlib.sha256(bytes().join(int(v).to_bytes(2,'little') for v in objects)).hexdigest(),'regions':counts,'source_graphics':hashes,'method':'Every archived object anchor retained, original dry blocked-cell union merged without expansion, native ground/water/road masks without traced paint or fading. Compatible trees/cliffs remain 3D; other scenery retains source art.'}
 return masks,atlas,'\n'.join(rows)+'\n',meta

def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--source',type=Path,default=ROOT.parent/'Magic Power');p.add_argument('--check',action='store_true');a=p.parse_args()
 masks,atlas,data,meta=prepare(a.source.resolve());images={**{k+'_surface.png':v for k,v in masks.items()},'props.png':atlas}
 if a.check:
  for name,expected in images.items():
   actual=Image.open(OUT/name);assert actual.size==expected.size and actual.tobytes()==expected.tobytes(),name
  assert (OUT/'data.gd').read_text()==data
  assert json.loads((OUT/'provenance.json').read_text())==json.loads(json.dumps(meta))
  from build_freyja_surface import build
  with tempfile.TemporaryDirectory() as folder:
   build(a.source.resolve(),Path(folder),300)
   for name in ['sokia_ground_index.png','sokia_ground_atlas.png']:
    actual=Image.open(OUT.parent/name);expected=Image.open(Path(folder)/name)
    assert actual.size==expected.size and actual.tobytes()==expected.tobytes(),name
  print('SOKIA_SOURCE_CHECK original tiles, all scenery anchors, blocked cells and native pixels preserved')
 else:
  OUT.mkdir(parents=True,exist_ok=True)
  for name,im in images.items():im.save(OUT/name,optimize=True)
  (OUT/'data.gd').write_text(data);(OUT/'provenance.json').write_text(json.dumps(meta,indent=2)+'\n')
  print(json.dumps({'regions':meta['regions'],'atlas_size':atlas.size,'native_graphics':len(meta['source_graphics'])}))
if __name__=='__main__':main()
