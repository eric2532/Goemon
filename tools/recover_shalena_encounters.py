"""Prepare pinned Tina/Shalena random-battle membership for existing native patrols."""
import argparse
from fractions import Fraction
import hashlib
import json
from math import gcd, lcm
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/references/crossgate_tina/events'
OUT = ROOT / 'assets/maps/falan/tina'
# Stable pack order; body heights relative to Kaz, as in the frontier catalog.
SPECIES = [
    (101012, '北極熊', 1.6), (101033, '地獄妖犬', .85),
    (101111, '血骷髏', 1.), (101123, '死靈', 1.),
    (101254, '兔耳蝙蝠', .85), (101314, '死亡蜂', .8),
    (101323, '死灰螳螂', 1.1), (101401, '死亡樹精', 1.9),
    (101403, '慘白樹精', 1.9), (101411, '蔓陀羅草', .8),
    (101631, '水晶螃蟹', .7), (101723, '風龍蜥', 1.05),
    (101802, '火焰哥布林', .7), (101822, '海盜', 1.),
    (101831, '幻歌妖', 1.1), (101833, '烈風鳥人', 1.1),
]


def build(archive):
    proofs = json.loads((SOURCE / 'references.json').read_text())
    for proof in proofs:
        assert hashlib.sha256((SOURCE / proof['file']).read_bytes()).hexdigest() == proof['sha256']

    def rows(name):
        return [r.split('\t') for r in (SOURCE / name).read_bytes().decode('gb18030').splitlines()
                if r and not r.startswith('#')]

    enemies = {r[2]: r for r in rows('enemy.txt')}
    bases = {r[1]: r for r in rows('enemybase.txt')}
    groups = {r[2]: r for r in rows('group.txt')}
    skins = {ident: i for i, (ident, _, _) in enumerate(SPECIES)}
    catalog = json.loads((archive / 'data/crossgate/catalog.json').read_text())['entries']
    species = []
    for ident, name, height in SPECIES:
        keys = [r['key'] for r in catalog if r['id'] == ident and r['key'].startswith('original:')
                and 2800 <= int(r['key'].split(':')[1]) < 3000]
        assert len(keys) == 1, (ident, keys)
        species.append(dict(id=ident, key=keys[0], name=name, height=height))
    zones = {}
    for row in rows('encount.txt'):
        if int(row[3]) not in (400, 402, 4201):
            continue
        choices = {}
        for i, group_id in enumerate(row[14:24]):
            if not group_id or not int(row[24+i] or 0):
                continue
            group = groups[group_id]
            members = [(enemy, int(group[15+j] or 0)) for j, enemy in enumerate(group[5:15])
                       if enemy not in ('', '0') and int(group[15+j] or 0)]
            total = sum(weight for _, weight in members)
            assert total > 0, group_id
            for enemy, weight in members:
                variant = enemies[enemy]
                token = (skins[int(bases[variant[3]][30])], int(variant[4]), int(variant[5]))
                choices[token] = choices.get(token, Fraction()) + Fraction(int(row[24+i])*weight, total)
        assert choices, row[0]
        denominator = lcm(*(v.denominator for v in choices.values()))
        weights = [int(v*denominator) for v in choices.values()]
        divisor = gcd(*weights)
        zones[int(row[0])] = dict(map=int(row[3]), bounds=list(map(int, row[4:8])),
                                 choices=[[*token, weight//divisor] for token, weight in zip(choices, weights)],
                                 source_row=row)
    assert len(zones) == 56 and sum(r['map'] == 4201 for r in zones.values()) == 1
    assert {s[0] for z in zones.values() for s in z['choices']} == set(range(len(SPECIES)))
    data = dict(species=species, zones=zones,
                note='Pinned corroborating server encounters and original BlueCG art; real-time posts/counts and combat stats are adaptations.',
                source_hashes={name: hashlib.sha256((SOURCE/name).read_bytes()).hexdigest()
                               for name in ['encount.txt', 'group.txt', 'enemy.txt', 'enemybase.txt']})
    lines = ['extends RefCounted', '## Generated by tools/recover_shalena_encounters.py.',
             'const SPECIES='+json.dumps(species, ensure_ascii=False), 'const ZONES={']
    for ident, zone in zones.items():
        x, y, xx, yy = zone['bounds']
        lines.append(f' {ident}:[{zone["map"]},Rect2i({x},{y},{xx-x+1},{yy-y+1}),'+json.dumps(zone['choices'])+'],')
    lines += ['}']
    return data, '\n'.join(lines)+'\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--archive', type=Path, default=ROOT.parent/'Magic Power')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data, script = build(args.archive)
    encoded = json.dumps(data, ensure_ascii=False, indent=2)+'\n'
    if args.check:
        assert (OUT/'encounters.json').read_text() == encoded
        assert (OUT/'encounters.gd').read_text() == script
    else:
        (OUT/'encounters.json').write_text(encoded)
        (OUT/'encounters.gd').write_text(script)
    print('PASS: 56 pinned Shalena/Tina encounter zones, 16 original species and weighted memberships')
