"""Recover Ghana's native building anchors for reuse of the existing Kili kit."""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/maps/falan'
GRAPHICS = {11289, 11290, 11292, 11293, 11294, 11295, 11297, 11298}


def prepare(source):
    sys.path.insert(0, str(source / 'tools'))
    import cg_library as library
    with library.connection() as db:
        file_id = db.execute('SELECT id FROM files WHERE path=?', ('BlueCrossgate/map/0/3000.dat',)).fetchone()[0]
    raw = library.source_file(file_id)[1].read_bytes()
    width, height, _, objects, _ = library.parse_map(raw)
    lookup = library.serial_index()
    placements, walls, fences, sources = [], [], [], {}
    for index, serial in enumerate(objects):
        if serial not in GRAPHICS and serial not in range(11234,11247) and serial not in [11363,11364]:
            continue
        entry = lookup[serial]
        x, y = index % width, index // width
        center_x = x + (max(1, entry['east']) - 1) * .5 if serial in GRAPHICS else x
        center_y = y - (max(1, entry['south']) - 1) * .5 if serial in GRAPHICS else y
        at = [(center_x - width // 2) * 3, (center_y - height // 2) * 3]
        (placements if serial in GRAPHICS else fences if serial in [11363,11364] else walls).append({'graphic': serial, 'source_tile': [x, y], 'at': at})
        image = library.image_from_record(entry['pack'], entry['row'])
        sources[serial] = {'pack': entry['pack'], 'row': entry['row'],
                           'rgba_sha256': hashlib.sha256(image.tobytes()).hexdigest(),
                           'origin': [entry['x'],entry['y']]}
    assert len(placements) == 8 and {r['graphic'] for r in placements} == GRAPHICS
    rows = ['extends RefCounted', '## Generated by tools/recover_ghana_fronts.py; map 3000 native anchors.', 'const BUILDINGS=[']
    rows += [f' [Vector2({r["at"][0]},{r["at"][1]}),{r["graphic"]}],' for r in placements]
    rows += [']', 'const WALLS={']
    rows += [f' Vector2({r["at"][0]},{r["at"][1]}):{r["graphic"]},' for r in walls]
    rows.append('}')
    rows.append('const FENCES={')
    rows += [f' Vector2({r["at"][0]},{r["at"][1]}):{r["graphic"]},' for r in fences]
    rows += ['}', 'const FENCE_POST_PIXELS={11363:67.0,11364:66.0}']
    assert len(fences) == 73 and sources[11363]['origin'][1] == -67 and sources[11364]['origin'][1] == -66
    meta = {'map': 'BlueCrossgate/map/0/3000.dat', 'map_sha256': hashlib.sha256(raw).hexdigest(),
            'size': [width, height], 'placements': placements, 'walls': walls, 'fences': fences, 'graphics': sources,
            'method': 'Original compound-footprint centres at three metres per tile. Reuse the complete matching Kili building meshes; existing Ghana collision and travel owners remain unchanged.'}
    return '\n'.join(rows) + '\n', meta


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT.parent / 'Magic Power')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data, meta = prepare(args.source.resolve())
    path = OUT / 'ghana_fronts'
    if args.check:
        assert path.with_suffix('.gd').read_text() == data
        assert json.loads(path.with_suffix('.json').read_text()) == json.loads(json.dumps(meta))
        print('PASS: eight Ghana buildings, 46 walls, 73 fences and source hashes reproduce')
    else:
        path.with_suffix('.gd').write_text(data)
        path.with_suffix('.json').write_text(json.dumps(meta, indent=2) + '\n')
        print('Recovered eight Ghana building pieces for the existing Kili mesh kit')


if __name__ == '__main__':
    main()
