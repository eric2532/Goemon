"""Unwarp reusable Il/Alyut surface paint from the preserved Blue CG building atlases."""
import json
import re
from pathlib import Path
from PIL import Image, ImageOps, ImageStat

CELL = 128
INSET = 8
# Source-image coordinates, clockwise from top left. Feature aspect is preserved.
PATCHES = {
    'plaster': (11272, [(135,312),(143,312),(143,324),(135,324)], False, (64,64)),
    'thatch': (11272, [(79,185),(128,220),(151,201),(102,165)], False, (96,64)),
    'round_thatch': (11271, [(145,252),(201,281),(228,262),(173,232)], False, (96,64)),
    'timber': (11271, [(271,130),(309,117),(337,135),(299,150)], False, (96,64)),
    'trim': (11272, [(95,117),(99,117),(99,129),(95,129)], False, (32,64)),
    'stone': (10607, [(204,320),(212,320),(212,334),(204,334)], False, (64,64)),
    'blue_roof': (10607, [(145,117),(173,138),(193,125),(165,104)], False, (64,64)),
    'window': (11272, [(68,88),(94,105),(94,146),(68,129)], True, (48,76)),
    'door': (11272, [(158,311),(182,328),(182,392),(158,375)], True, (48,104)),
    'round_window': (11271, [(166,319),(207,319),(207,378),(166,378)], True, (60,86)),
    'church_window': (10607, [(23,169),(44,184),(44,267),(23,252)], True, (32,112)),
    'medallion': (10607, [(247,238),(299,208),(299,273),(247,303)], True, (96,96)),
    'canopy': (11275, [(20,243),(74,216),(110,243),(53,270)], False, (96,64)),
    'dormer_cap': (11272, [(145,34),(158,42),(172,31),(158,23)], False, (64,64)),
}


def surface_atlas(sources, patches):
    result = Image.new('RGBA', (CELL*4, CELL*((len(patches)+3)//4)))
    rows = ['extends RefCounted', '## Generated by tools/build_village_building_surfaces.py; original Blue CG paint.',
            'const CELL=128', 'const TILES={']
    for i, (name, (serial, quad, feature, size)) in enumerate(patches.items()):
        ul,ur,lr,ll = quad
        patch = sources[serial].transform(size, Image.Transform.QUAD,
                                         (*ul,*ll,*lr,*ur), Image.Resampling.BICUBIC)
        if name == '10300_emblem':
            mask = Image.new('L', patch.size)
            pixels = []
            for y in range(patch.height):
                for x in range(patch.width):
                    r,g,b,a = patch.getpixel((x,y))
                    face = ((x/patch.width-.47)/.30)**2 + ((y/patch.height-.32)/.36)**2 < 1
                    ornament = (r>g*1.08 and g>b*1.25 and r>100) or (b>g*1.12 and r>g*1.10 and r>50)
                    pixels.append(a if face or ornament else 0)
            mask.putdata(pixels); patch.putalpha(mask)
        if name == '10300_scroll':
            patch.putalpha(ImageOps.grayscale(patch).point(lambda v: max(0, min(255, (v-125)*4))))
        if name == '10312_vines':
            mask = Image.new('L', patch.size)
            mask.putdata([a if g > r*1.02 and g > b*1.08 else 0 for r,g,b,a in patch.getdata()])
            patch.putalpha(mask)
        if feature:
            assert patch.getchannel('A').getbbox() is not None, name
            patch.thumbnail((CELL-INSET*2, CELL-INSET*2), Image.Resampling.LANCZOS)
            tile = Image.new('RGBA', (CELL-INSET*2, CELL-INSET*2))
            tile.alpha_composite(patch, ((tile.width-patch.width)//2, (tile.height-patch.height)//2))
        else:
            assert patch.getchannel('A').getextrema()[0] == 255, name
            if name in ['plaster','trim','stone','snowroof','10003_base','magic_stone','special_brick','villa_stone','tina_log_bark','tina_log_end','tina_fence_wood','tina_bay_fence','tina_boat_white','tina_sign_bark','tina_ruin_stone','tina_barrel_brown','tina_barrel_red','tina_barrel_green','tina_box_plank','tina_box_inner','tina_ruin_snow','tina_wash_wood','tina_pail_wood','tina_wash_water','tina_hollow_bark','tina_soft_snow','tina_mitten_red','tina_snowman_mouth','tina_stack_end_green','tina_camp_ash','tina_camp_charcoal','tina_blue_porch']:
                # Small neutral crops retain their source tone without magnifying palette dithering.
                tone=tuple(round(c) for c in ImageStat.Stat(patch).mean[:3])+(255,)
                patch=Image.blend(patch,Image.new('RGBA',patch.size,tone),.96 if name=='tina_soft_snow' else .72)
            half = patch.resize(((CELL-INSET*2)//2, (CELL-INSET*2)//2), Image.Resampling.LANCZOS)
            tile = Image.new('RGBA', (CELL-INSET*2, CELL-INSET*2))
            tile.paste(half, (0,0));tile.paste(ImageOps.mirror(half),(half.width,0))
            tile.paste(ImageOps.flip(tile.crop((0,0,tile.width,half.height))), (0,half.height))
        # Extruded borders protect each tile from adjacent atlas paint during filtering.
        padded = tile.resize((CELL,CELL),Image.Resampling.NEAREST)
        padded.paste(tile,(INSET,INSET))
        for x in range(CELL):
            for y in range(CELL):
                if x<INSET or y<INSET or x>=CELL-INSET or y>=CELL-INSET:
                    padded.putpixel((x,y),tile.getpixel((min(tile.width-1,max(0,x-INSET)),min(tile.height-1,max(0,y-INSET)))))
        result.paste(padded, (i%4*CELL,i//4*CELL))
        rows.append(f' "{name}":Vector2({i%4*CELL},{i//4*CELL}),')
    return result, rows


def build(output):
    sources = {}
    for village in ['il', 'alyut']:
        atlas = Image.open(output / f'{village}_buildings.png').convert('RGBA')
        text = (output / f'{village}_restoration_data.gd').read_text()
        for serial, x, y, w, h in re.findall(r'(\d+):\[Rect2\((\d+),(\d+),(\d+),(\d+)\)', text):
            x,y,w,h = map(int, (x,y,w,h))
            sources[int(serial)] = atlas.crop((x,y,x+w,y+h))
    result, rows = surface_atlas(sources, PATCHES)
    result.save(output/'village_building_surfaces.png', optimize=True)
    (output/'village_building_surfaces.gd').write_text('\n'.join(rows+['}'])+'\n')
    (output/'village_building_surfaces.json').write_text(json.dumps(PATCHES,indent=2)+'\n')
    print(f'Prepared {len(PATCHES)} rectified Blue CG surfaces; original atlases unchanged.')


if __name__ == '__main__':
    build(Path(__file__).resolve().parents[1]/'assets/maps/falan')
