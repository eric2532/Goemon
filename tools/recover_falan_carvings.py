"""Recover source facade carvings and bounded shallow relief; preserve the original art."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
from PIL import Image
from build_freyja_destinations import load_map
from build_village_building_surfaces import surface_atlas
from prepare_arena_carvings import shallow_depth
from recover_falan_landmarks import rect

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/maps/falan'
PATCHES={
 'office_mask':(10607,[(200,255),(220,268),(220,306),(200,293)],True,(48,96)),
 'guild_relief':(10604,[(123,246),(143,259),(143,323),(123,310)],True,(40,112)),
 'bank_frieze':(10010,[(290,249),(343,215),(343,234),(290,268)],True,(112,32)),
 'mansion_window':('mansion',[(220,343),(240,344),(240,385),(220,383)],True,(40,96)),
 'mansion_frieze':('mansion',[(167,267),(213,273),(213,292),(167,286)],True,(112,40)),
 'mansion_window':('mansion',[(220,343),(240,344),(240,385),(220,383)],True,(40,96)),
 'mansion_portal':('mansion',[(277,324),(307,340),(307,384),(277,368)],True,(64,96)),
 'office_frieze':(10607,[(235,310),(325,251),(325,274),(235,333)],True,(112,32)),
}
DEPTH={'office_mask':.18,'guild_relief':.16,'bank_frieze':.18,'mansion_frieze':.10,'mansion_window':0.0,'mansion_portal':.15,'office_frieze':.16}
SAMPLE_STEP={'bank_frieze':1,'office_frieze':1}


def mansion_reference(library):
    lookup=library.serial_index()
    w,_,ground,objects,_=load_map(library,1000)
    placed=[]
    for layer,plane in enumerate([ground,objects]):
        for i,serial in enumerate(plane):
            entry=lookup.get(serial)
            if not entry:continue
            x,y=i%w,i//w
            placed.append((0 if layer==0 or entry['ground'] else 1,
                           11*y-9*x-min(entry['east'],entry['south'])*10,
                           (x+y)*32+entry['x'],(y-x)*24+entry['y'],serial))
    placed.sort()
    _,_,x,y,_=next(r for r in placed if r[-1]==10600)
    entry=lookup[10600]
    box=(x-90,y-50,x+entry['w']+90,y+entry['h']+200)
    canvas=Image.new('RGBA',(box[2]-box[0],box[3]-box[1]));used={}
    for _,_,px,py,serial in placed:
        entry=lookup[serial]
        if px>=box[2] or py>=box[3] or px+entry['w']<=box[0] or py+entry['h']<=box[1]:continue
        image=library.image_from_record(entry['pack'],entry['row'])
        canvas.alpha_composite(image,(px-box[0],py-box[1]))
        used[serial]={'pack':entry['pack'],'row':entry['row'],'rgba_sha256':hashlib.sha256(image.tobytes()).hexdigest()}
    return canvas,{'map':1000,'viewport':box,'graphics':used,'rgba_sha256':hashlib.sha256(canvas.tobytes()).hexdigest()}


def prepare(source):
    sys.path.insert(0,str(source/'tools'))
    import cg_library as library
    lookup=library.serial_index();images={};provenance={}
    for serial in [10607,10604,10010]:
        entry=lookup[serial];image=library.image_from_record(entry['pack'],entry['row'])
        images[serial]=image
        provenance[serial]={'pack':entry['pack'],'row':entry['row'],'rgba_sha256':hashlib.sha256(image.tobytes()).hexdigest()}
    images['mansion'],provenance['mansion']=mansion_reference(library)
    atlas,_=surface_atlas(images,PATCHES)
    depths=Image.new('L',atlas.size)
    rows=['extends RefCounted','## Generated by tools/recover_falan_carvings.py; original paint and shallow relief.',
          'const ATLAS=preload("res://assets/maps/falan/city_carvings.png")',
          'const DEPTH=preload("res://assets/maps/falan/city_carvings_depth.png")','const FEATURES={']
    for i,(name,patch) in enumerate(PATCHES.items()):
        x,y,w,h=rect(i,patch[3])
        stone=atlas.crop((x,y,x+w,y+h)).convert('L')
        depth=shallow_depth(stone)
        assert depth.getextrema()==(0,255),name
        depths.paste(depth,(x,y))
        sampling=f',{SAMPLE_STEP[name]}' if name in SAMPLE_STEP else ''
        rows.append(f' "{name}":[Rect2i({x},{y},{w},{h}),{DEPTH[name]}{sampling}],')
    rows.append('}')
    stone_atlas=atlas.copy()
    for i,(name,patch) in enumerate(PATCHES.items()):
        if DEPTH[name]==0:continue
        x,y,w,h=rect(i,patch[3])
        for py in range(y,y+h):
            for px in range(x,x+w):
                r,g,b,_=atlas.getpixel((px,py))
                tone=.80+.20*(r*.2126+g*.7152+b*.0722)/255
                alpha=255 if depths.getpixel((px,py))>=12 else 0
                stone_atlas.putpixel((px,py),(round(224*tone),round(213*tone),round(184*tone),alpha))
    rows.insert(4,'const STONE=preload("res://assets/maps/falan/city_carvings_stone.png")')
    meta={'sources':provenance,'patches':PATCHES,'maximum_relief_metres':DEPTH,'source_pixel_sampling':SAMPLE_STEP,
          'stone_finish':'Original pale-stroke mask on fitted limestone; native color crops remain preserved separately.',
          'method':'Original rectified facade paint with shallow pale-stroke relief, reusing the arena depth recipe. Depth is an interpretation of 2D shading, not original recovered sculpture.'}
    return atlas,depths,stone_atlas,'\n'.join(rows)+'\n',meta


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',type=Path,default=ROOT.parent/'Magic Power');parser.add_argument('--check',action='store_true')
    args=parser.parse_args();atlas,depth,stone_atlas,data,meta=prepare(args.source.resolve())
    outputs={'city_carvings.png':atlas,'city_carvings_depth.png':depth,'city_carvings_stone.png':stone_atlas}
    if args.check:
        for name,image in outputs.items():
            with Image.open(OUT/name) as actual:assert actual.tobytes()==image.tobytes(),name
        assert (OUT/'city_carvings.gd').read_text()==data
        assert json.loads((OUT/'city_carvings.json').read_text())==json.loads(json.dumps(meta))
        print('PASS: native facade paint, shallow relief and composed mansion sources reproduce exactly')
    else:
        for name,image in outputs.items():image.save(OUT/name,optimize=True)
        (OUT/'city_carvings.gd').write_text(data);(OUT/'city_carvings.json').write_text(json.dumps(meta,indent=2)+'\n')
        print('Recovered original carving panels and mansion windows with bounded shallow relief')

if __name__=='__main__':main()
