def villages(library, lookup, output):
    from build_freyja_surface import build as build_surface
    from build_coastal_villages import BUILDINGS
    profiles = {
        11290:("kili_house",0,10.8,8.1,8.6),11293:("ghana_hospital",-90,11.8,10.8,7.8),
        11289:("kili_house",-90,10.8,8.1,8.6),11294:("kili_chief",-90,21,10.8,12),
        11292:("kili_tavern",-90,13,8,8.8),11295:("kili_shop",-90,21,9.8,9.2),
        11298:("kili_shop",-90,21,9.8,9.2),11279:("falan_townhouse",0,14,15,14),
        11276:("falan_townhouse",-90,14,15,14),11280:("falan_townhouse",-90,14,15,14),
        11286:("falan_townhouse",-90,14,15,14),11283:("falan_shop",-90,15,14,15),
        11284:("falan_shop",0,15,14,15),
    }
    lines = ["extends RefCounted", "## Original village exterior footprints; generated by build_undersea_details.py.", "const BUILDINGS={"]
    scenery = {}
    for area, ident in (("kili",3200),("venoa",2100)):
        build_surface(Path(library.__file__).resolve().parents[1],output,ident)
        w,h,ground,objects,_=load_map(library,ident)
        assert sum(serial in profiles for serial in objects) == 7, area
        scenery[area]=[]
        lines.append(f' "{area}":[')
        for i,serial in enumerate(objects):
            if serial not in lookup:continue
            x,z=i%w,i//w
            entry=lookup[serial]
            ew,ns=max(1,entry["east"]),max(1,entry["south"])
            if serial in profiles:
                kind,yaw,bw,bh,bd=profiles[serial]
                cx,cz=(x+(ew-1)*.5-w//2)*3,(z-(ns-1)*.5-h//2)*3
                wall,rise=BUILDINGS[serial]
                height=(wall+rise)*.045+(5.4 if serial==11293 else 1.4)
                sx,sz=ew*3/(bd if yaw else bw),ns*3/(bw if yaw else bd)
                lines.append(f'  ["{kind}",Vector2({cx},{cz}),Vector3({sx:.5f},{height/bh:.5f},{sz:.5f}),{yaw},{serial}],')
            elif (12500<=serial<=12565 or 11230<=serial<=11265 or 11363<=serial<=11372
                  or 11625<=serial<=11710 or 12160<=serial<=12180 or 11188<=serial<=11208
                  or 10058<=serial<=10074 or 10085<=serial<=10094 or serial==11297):
                scenery[area].append(f"  [Vector2i({x},{z}),{serial},Vector2i({ew},{ns}),{entry['h']},false],")
        lines.append(" ],")
    lines += ["}","const SCENERY={"]
    for area,rows in scenery.items():lines += [f' "{area}":[',*rows," ],"]
    lines += ["}"]
    (output / "coastal_village_data.gd").write_text("\n".join(lines)+"\n")
    print("Village source scenery:", {key:len(rows) for key,rows in scenery.items()})


