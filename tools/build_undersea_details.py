    mask = Image.open(output / "sokia_coast_surface.png").convert("RGBA")
    radius = mask.width//2
    trace = Image.new("L",mask.size)
    ImageDraw.Draw(trace).line([(x-258+radius,z-280+radius) for x,z in path],fill=184,width=3)
