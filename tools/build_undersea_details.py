def entrances(library, lookup, output):
    for serial, origin, across, down in ((13268, (4, 25), (27, -19), (5, 5)),
                                          (13269, (8, 30), (26, 18), (2, -3))):
        entry = lookup[serial]
        image = library.image_from_record(entry["pack"], entry["row"], PALETTE)
        patch = Image.new("RGB", (32, 32))
        for y in range(32):
            for x in range(32):
                point = tuple(round(origin[i] + (across[i] * x + down[i] * y) / 31) for i in (0, 1))
                pixel = image.getpixel(point)
                assert pixel[3] == 255, (serial, point)
                patch.putpixel((x, y), pixel[:3])
        tile = Image.new("RGB", (64, 64))
        tile.paste(patch, (0, 0));tile.paste(ImageOps.mirror(patch), (32, 0))
        tile.paste(ImageOps.flip(patch), (0, 32));tile.paste(ImageOps.flip(ImageOps.mirror(patch)), (32, 32))
        tile.save(output / f"undersea_stair_{serial}.png", optimize=True)
    lines = ["extends RefCounted", "## Dark opening silhouettes traced from the original outdoor map composites.", "const MOUTHS={"]
    for map_id, x, z in ((100, 343, 497), (100, 299, 538), (100, 251, 493), (300, 240, 265)):
        with library.connection() as db:
            ident = db.execute("SELECT id FROM files WHERE path=?", (f"BlueCrossgate/map/0/{map_id}.dat",)).fetchone()[0]
        left, top = library.map_plan(ident)["bounds"][:2]
        image = library.render_map(ident, 0, 0, (x + z) * 32 - left - 250, (z - x) * 24 - top - 260, 500, 400)
        dark = {(u, v) for v in range(20, 300) for u in range(100, 360) if image.getpixel((u, v))[:3] == (20, 20, 20)}
        opening = set()
        while dark:
            seed = dark.pop();component = {seed};pending = [seed]
            while pending:
                u, v = pending.pop()
                for point in ((u-1,v),(u+1,v),(u,v-1),(u,v+1)):
                    if point in dark:
                        dark.remove(point);component.add(point);pending.append(point)
            if len(component) > len(opening):opening = component
        assert len(opening) > 2000, (map_id, x, z)
        x0, x1 = min(u for u, v in opening), max(u for u, v in opening)
        y0, y1 = min(v for u, v in opening), max(v for u, v in opening)
        center = (x0 + x1) * .5
        sides = [[], []]
        for step in range(8):
            row = round(y1 - 5 - step * (y1 - y0 - 10) / 7)
            pixels = [u for u, v in opening if abs(v-row) <= 2]
            assert pixels
            low, high = (min(pixels)-center)*3.6/(x1-x0), (max(pixels)-center)*3.6/(x1-x0)
            if step < 3:low = min(low, -1.2);high = max(high, 1.2)
            height = (y1 - 5 - row) * .043
            sides[0].append((low, height));sides[1].append((high, height))
        profile = sides[0] + sides[1][::-1]
        points = ",".join(f"Vector2({u:.4f},{v:.4f})" for u, v in profile)
        lines.append(f" Vector2i({x},{z}):[{points}],")
    lines.append("}")
    (output / "undersea_entrances.gd").write_text("\n".join(lines) + "\n")


def blue_surfaces(library, lookup, output):
    data = (output / "room_art_data.gd").read_text()
    indices = {}
    for name in ("FLOORS", "WALLS"):
        block = re.search(r"const " + name + r"=\{(.*?)\n\}", data, re.S)[1]
        indices[name] = {int(i): zlib.decompress(base64.b64decode(encoded))
                         for i, encoded in re.findall(r'(\d+):"([^"]+)"', block)}
    mappings = {"floor": {}, "wall": {}}
    profiles = {}
    prop_serials = set()
    for ident in FLOORS:
        _, _, ground, objects, _ = load_map(library, ident)
        prop_serials.update(objects)
        for kind, name, source in (("floor", "FLOORS", ground), ("wall", "WALLS", objects)):
            slots = struct.unpack("<" + "H" * len(source), indices[name][ident])
            for serial, slot in zip(source, slots):
                if not serial or not slot:
                    continue
                index = slot - 1
                assert index not in mappings[kind] or mappings[kind][index] == serial
                mappings[kind][index] = serial
    for kind, mapping in mappings.items():
        atlas = Image.open(output / f"room_{kind}_atlas.png").convert("RGBA" if kind == "wall" else "RGB")
        for index, serial in mapping.items():
            entry = lookup[serial]
            original = library.image_from_record(entry["pack"], entry["row"], PALETTE)
            if kind == "floor":
                atlas.paste(project_tile(original), (index % 32 * 36, index // 32 * 36))
            else:
                for side in (0, 1):
                    face = index * 2 + side
                    projected = project_wall(original, entry, side, cave=True)
                    for y in range(projected.height):
                        for x in range(projected.width):
                            r, g, b, a = projected.getpixel((x, y))
                            if r + g <= 16:projected.putpixel((x, y), (r, g, b, 0))
                    atlas.paste(projected, (face % 16 * 36, face // 16 * 100))
                    values = []
                    for height in (10, 8.58, 7.45, 6.25, 4.65, 3.15, 1.85, .66, 0):
                        for x in range(5):
                            pixel = projected.getpixel((2 + round(x * 31 / 4), 2 + round((1 - height / 10) * 95)))
                            values.append(round(.12 + (1 - sum(pixel[:3]) / 765) * .42, 4))
                    assert len(values) == 45 and all(.12 <= value <= .54 for value in values)
                    profiles[face] = values
        atlas.save(output / f"undersea_{kind}_atlas.png", optimize=True)
    atlas = Image.open(output / "cave_rock_atlas.png").copy()
    for variant, (serial, x, y) in enumerate(((13019, 28, 28), (13007, 18, 96))):
        entry = lookup[serial]
        original = library.image_from_record(entry["pack"], entry["row"], PALETTE)
        patch = original.crop((x, y, x + 18, y + 58)).convert("RGB").resize((32, 64), Image.Resampling.BICUBIC)
        strip = Image.new("RGB", (64, 64))
        strip.paste(patch, (0, 0));strip.paste(ImageOps.mirror(patch), (32, 0))
        atlas.paste(strip, (128, variant * 128))
        atlas.paste(ImageOps.flip(strip), (128, variant * 128 + 64))
    atlas.save(output / "undersea_rock_atlas.png", optimize=True)
    roof = atlas.copy()
    for variant, serial in enumerate((13000, 13019)):
        entry = lookup[serial]
        original = library.image_from_record(entry["pack"], entry["row"], PALETTE)
        # The source's solid navy back diamond is occluded space, not ceiling stone.
        candidates = []
        for y in range(8, 40):
            for x in range(original.width - 8):
                pixels = list(original.crop((x, y, x + 8, y + 8)).getdata())
                stone = sum(a > 128 and r + g > 16 for r, g, b, a in pixels)
                candidates.append(((stone, -abs(x + 4 + entry["x"]) - abs(y - 30)), x, y))
        score, x, y = max(candidates)
        assert score[0] == 64, serial
        patch = original.crop((x, y, x + 8, y + 8)).convert("RGB").resize((32, 32), Image.Resampling.BICUBIC)
        cap = Image.new("RGB", (64, 64))
        cap.paste(patch, (0, 0));cap.paste(ImageOps.mirror(patch), (32, 0))
        cap.paste(ImageOps.flip(patch), (0, 32));cap.paste(ImageOps.flip(ImageOps.mirror(patch)), (32, 32))
        roof.paste(cap, (128, variant * 128))
        roof.paste(ImageOps.flip(cap), (128, variant * 128 + 64))
    roof.save(output / "undersea_roof_atlas.png", optimize=True)
    lines = ["extends RefCounted", "", "static var WALL_RELIEF={"]
    lines.extend(f" {face}:PackedFloat32Array({values})," for face, values in sorted(profiles.items()))
    lines.append("}")
    (output / "undersea_shapes.gd").write_text("\n".join(lines) + "\n")
    atlas = Image.open(output / "boss_room_props.png").copy()
    props = (output / "boss_room_props.gd").read_text()
    for serial, x, y, width, height, flat in re.findall(
            r'(\d+):\[Rect2\((\d+),(\d+),(\d+),(\d+)\),Vector2i\(\d+,\d+\),(true|false)\]', props):
        serial = int(serial)
        if serial not in prop_serials:
            continue
        entry = lookup[serial]
        original = library.image_from_record(entry["pack"], entry["row"], PALETTE)
        if flat == "true":
            center_y = original.height - 23 if entry["ground"] and original.height >= 70 else min(original.height - 1, -entry["y"])
            original = (habaru_flat_prop(original, entry) if serial in (16642, 16788)
                        else project_boss_overlay(original, -entry["x"], center_y))
        else:
            original = original.crop(original.getbbox())
        assert original.size == (int(width), int(height)), serial
        atlas.paste(original, (int(x), int(y)))
    atlas.save(output / "undersea_props.png", optimize=True)
    shore = Image.new("RGBA", (16 * 36, 5 * 100))
    for serial in range(13036, 13072):
        entry = lookup[serial]
        original = library.image_from_record(entry["pack"], entry["row"], PALETTE)
        center = -entry["x"]
        top = -entry["y"]
        bottom = original.height - 23
        for side in (0, 1):
            face = (serial - 13036) * 2 + side
            for y in range(100):
                v = max(0, min(95, y - 2)) / 95
                for x in range(36):
                    u = max(0, min(31, x - 2)) / 31
                    dx = (u if side else u - 1) * 29
                    px = max(0, min(original.width - 1, round(center + dx)))
                    py = max(0, min(original.height - 1, round(top - abs(dx) * .75 + v * (bottom - top))))
                    shore.putpixel((face % 16 * 36 + x, face // 16 * 100 + y), original.getpixel((px, py)))
    shore.save(output / "undersea_shore_faces.png", optimize=True)
    print("Blue CG palette", PALETTE, "source tiles:", {kind: len(rows) for kind, rows in mappings.items()})


def build(source, output):
    sys.path.insert(0, str(source / "tools"))
    import cg_library as library
    serials = (13004, 13016, 13028)
    lookup = library.serial_index()
    blue_surfaces(library, lookup, output)
    entrances(library, lookup, output)
    surroundings(library, lookup, output)
    villages(library, lookup, output)
    from build_coastal_villages import build as coastal_art
    coastal_art(library,lookup,output)
    atlas = Image.new("RGBA", (108, 36))
    for index, serial in enumerate(serials):
        entry = lookup[serial]
        original = library.image_from_record(entry["pack"], entry["row"], PALETTE)
        flat = project_boss_overlay(original, -entry["x"], min(original.height - 1, -entry["y"]))
        atlas.paste(flat, (index * 36 + 2, 2))
    atlas.save(output / "undersea_edges.png", optimize=True)
    rows = ["extends RefCounted", "", "const TILES={"]
    for ident in (15003, 15593):
        width, _, _, objects, *_ = load_map(library, ident)
        rows.append(f" {ident}:[")
        rows.extend(f"  Vector3i({i % width},{i // width},{serials.index(serial)}),"
                    for i, serial in enumerate(objects) if serial in serials)
        rows.append(" ],")
    rows.append("}")
    (output / "undersea_edges.gd").write_text("\n".join(rows) + "\n")


if __name__ == "__main__":
    build(Path(sys.argv[1]).resolve(), Path(__file__).resolve().parents[1] / "assets/maps/falan")
