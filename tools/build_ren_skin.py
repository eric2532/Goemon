"""Create Ren, an optional Goemon skin; preserve the source and exact body/rig.
Run: Blender --background --python tools/build_ren_skin.py
"""
import bpy, math, hashlib, json
import numpy as np
from pathlib import Path
from mathutils import Vector
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'assets/blender/characters/kai.blend'
original_hash = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
bpy.ops.wm.open_mainfile(filepath=str(SOURCE))
rig = next(o for o in bpy.data.objects if o.type == 'ARMATURE')
body = bpy.data.objects['Skin']
body_positions = [tuple(v.co) for v in body.data.vertices]
body_weights = [[(g.group, g.weight) for g in v.groups] for v in body.data.vertices]
bone_matrices = [b.matrix_local.copy() for b in rig.data.bones]
# Reuse colors sampled directly from Goemon's packed original atlas.
source_image = next(n.image for n in body.data.materials[0].node_tree.nodes if n.type == 'TEX_IMAGE')
pixels = np.array(source_image.pixels[:]).reshape(source_image.size[1], source_image.size[0], 4)
colors, counts = np.unique(np.round(pixels.reshape(-1,4),5), axis=0, return_counts=True)
def dominant(predicate):
    ids = [i for i,c in enumerate(colors) if predicate(c)]
    return np.clip(colors[max(ids, key=lambda i: counts[i])].copy(),0,1)
blue = dominant(lambda c: c[2]>.65 and c[0]<.3 and c[1]<.3)
red = dominant(lambda c: c[0]>.8 and c[1]<.2 and c[2]<.2)
gold_image=next(n.image for n in bpy.data.objects['Hair_Gold'].data.materials[0].node_tree.nodes if n.type=='TEX_IMAGE')
gold_pixels=np.array(gold_image.pixels[:]).reshape(-1,4)
gold_colors,gold_counts=np.unique(np.round(gold_pixels,5),axis=0,return_counts=True)
gold_ids=[i for i,c in enumerate(gold_colors) if c[0]>.8 and c[1]>.7 and c[2]<.25]
gold=np.clip(gold_colors[max(gold_ids,key=lambda i:gold_counts[i])],0,1)
skin = dominant(lambda c: c[0]>.85 and .55<c[1]<.9 and .25<c[2]<.7)
white = dominant(lambda c: min(c[:3])>.95)
ink = dominant(lambda c: max(c[:3])<.18)

def material(name, color):
    m=bpy.data.materials.new(name);m.use_nodes=True
    p=m.node_tree.nodes.get('Principled BSDF');p.inputs['Base Color'].default_value=tuple(color)
    p.inputs['Roughness'].default_value=1;p.inputs['Specular IOR Level'].default_value=0
    m.diffuse_color=tuple(color)
    return m

def texture_material(name, image_pixels):
    h,w,_=image_pixels.shape
    im=bpy.data.images.new(name,width=w,height=h,alpha=True)
    # Generated byte images store sRGB; sampled source pixels are scene-linear.
    encoded=image_pixels.copy()
    rgb=np.clip(encoded[:,:,:3],0,1)
    encoded[:,:,:3]=np.where(rgb<=.0031308,rgb*12.92,1.055*np.power(rgb,1/2.4)-.055)
    im.pixels.foreach_set(encoded.astype(np.float32).ravel());im.update()
    path=ROOT/'assets/textures/characters'/f'{name}.png'
    im.filepath_raw=str(path);im.file_format='PNG';im.save();im.pack()
    m=material(name,white);p=m.node_tree.nodes.get('Principled BSDF')
    n=m.node_tree.nodes.new('ShaderNodeTexImage');n.image=im;n.interpolation='Linear'
    m.node_tree.links.new(n.outputs['Color'],p.inputs['Base Color'])
    return m

# Original face geometry, with fresh planar UVs and an authored geometric face.
N=512
Y,X=np.mgrid[0:N,0:N]/(N-1)
face=np.empty((N,N,4));face[:]=skin

def polygon(points,color):
    inside=np.zeros(X.shape,dtype=bool)
    for (ax,ay),(bx,by) in zip(points,points[1:]+points[:1]):
        inside ^= ((ay>Y)!=(by>Y)) & (X<(bx-ax)*(Y-ay)/(by-ay+1e-12)+ax)
    face[inside]=color

def ellipse(cx,cy,rx,ry,color):
    face[((X-cx)/rx)**2+((Y-cy)/ry)**2<=1]=color

# Narrow, alert eyes and straight brows replace the round eyes and curled grin.
for s in [-1,1]:
    cx=.5+s*.205
    points=[(cx-.115,.51),(cx+.105,.535),(cx+.10,.385),(cx-.07,.375)]
    polygon(points,ink)
    polygon([(cx-.095,.493),(cx+.085,.516),(cx+.079,.401),(cx-.055,.393)],white)
    ellipse(cx+.015,.447,.047,.065,blue)
    ellipse(cx+.016,.449,.023,.051,ink)
    ellipse(cx+.001,.478,.012,.017,white)
    polygon([(cx-.108,.59),(cx+.10,.568),(cx+.103,.601),(cx-.085,.64)],ink)
    polygon([(cx-.09,.31),(cx+.035,.33),(cx+.06,.309),(cx-.075,.287)],red)
polygon([(.476,.354),(.504,.337),(.519,.362),(.508,.314),(.48,.326)],ink)
polygon([(.418,.221),(.548,.222),(.576,.254),(.559,.211),(.455,.203)],ink)
face_mat=texture_material('ren_face',face)
plain_skin=material('Ren • original skin tone',skin)
face_id=len(body.data.materials);body.data.materials.append(face_mat)
skin_id=len(body.data.materials);body.data.materials.append(plain_skin)
for p in body.data.polygons:
    if all(v<33 for v in p.vertices):
        p.material_index=face_id if p.normal.y>.10 else skin_id
        for li in p.loop_indices:
            v=body.data.vertices[body.data.loops[li].vertex_index].co
            # Face from left temple to right temple, chin to forehead.
            body.data.uv_layers.active.data[li].uv=((v.x+.7327)/1.4219,(v.z-1.4522)/.8984)

# Red linked chevrons over the existing white sleeves and gaiters.
pattern=np.empty((256,256,4));pattern[:]=white
V,U=np.mgrid[0:256,0:256]/256
line=np.abs(((V*4+np.abs((U*4)%1-.5))%1)-.5)<.055
pattern[line]=red
pattern_mat=texture_material('ren_sleeve_weave',pattern)
pattern_id=len(body.data.materials);body.data.materials.append(pattern_mat)
for p in body.data.polygons:
    if p.material_index!=0:continue
    uvs=[body.data.uv_layers.active.data[i].uv.copy() for i in p.loop_indices]
    if all(uv.x<.39 and uv.y<.16 for uv in uvs):
        p.material_index=pattern_id
        for li,uv in zip(p.loop_indices,uvs):body.data.uv_layers.active.data[li].uv=(uv.x/.39,uv.y/.16)

# New swept crown, compact side locks, and a long diagonal forelock.
# Fit each hair variant to the original variant's exact XYZ bounding box.
def make_hair(name,color):
    old=bpy.data.objects[name]
    lo=Vector(tuple(min(v.co[a] for v in old.data.vertices) for a in range(3)))
    hi=Vector(tuple(max(v.co[a] for v in old.data.vertices) for a in range(3)))
    verts=[];faces=[]
    rings=[(2.18,.68,.54),(2.48,.94,.78),(2.82,.83,.70),(3.04,.54,.47)]
    for z,rx,ry in rings:
        for i in range(12):
            a=i*math.tau/12
            verts.append((math.cos(a)*rx, math.sin(a)*ry,z+.065*math.cos(a)))
    for j in range(3):
        for i in range(12):faces.append((j*12+i,j*12+(i+1)%12,(j+1)*12+(i+1)%12,(j+1)*12+i))
    verts.append((.35,-.13,3.30))
    for i in range(12):faces.append((36+i,36+(i+1)%12,48))
    # Broad sculpted locks form a side sweep instead of a radial starburst.
    for points in [
        [(-.75,.30,2.89),(.46,.33,3.05),(.76,.80,2.16),(-.19,.78,2.51),(.22,.88,2.77)],
        [(-.90,.10,2.68),(-.50,.65,2.92),(-.50,.86,2.24),(-1.03,.49,2.45),(-.74,.80,2.63)],
        [(.49,-.26,2.93),(.93,-.17,2.73),(1.0,.51,2.25),(.56,.62,2.45),(.88,.36,2.65)],
        [(-.73,-.50,2.67),(.53,-.64,2.92),(.81,-.84,2.36),(-.76,-.94,2.13),(-.03,-.98,2.59)],
    ]:
        k=len(verts);verts.extend(points)
        faces.extend([(k,k+1,k+4),(k+1,k+2,k+4),(k+2,k+3,k+4),(k+3,k,k+4),(k+3,k+2,k+1,k)])
    generated_lo=Vector(tuple(min(v[a] for v in verts) for a in range(3)))
    generated_hi=Vector(tuple(max(v[a] for v in verts) for a in range(3)))
    verts=[tuple(lo[a]+(v[a]-generated_lo[a])/(generated_hi[a]-generated_lo[a])*(hi[a]-lo[a]) for a in range(3)) for v in verts]
    mesh=bpy.data.meshes.new(name+'_Ren');mesh.from_pydata(verts,[],faces);mesh.update();mesh.uv_layers.new()
    bpy.data.objects.remove(old,do_unlink=True)
    o=bpy.data.objects.new(name,mesh);bpy.context.collection.objects.link(o)
    o.parent=rig;group=o.vertex_groups.new(name='Head');group.add(list(range(len(verts))),1,'REPLACE')
    mod=o.modifiers.new('Reference_Rig','ARMATURE');mod.object=rig
    mesh.materials.append(material('Ren • '+name,color))
    o.hide_render=name=='Hair_Gold';o.hide_set(name=='Hair_Gold')
    actual_lo=Vector(tuple(min(v.co[a] for v in mesh.vertices) for a in range(3)))
    actual_hi=Vector(tuple(max(v.co[a] for v in mesh.vertices) for a in range(3)))
    assert (actual_lo-lo).length<1e-6 and (actual_hi-hi).length<1e-6
    return {'min':list(lo),'max':list(hi),'vertices':len(verts)}
hair_bounds={'normal':make_hair('Hair_Normal',blue),'surge':make_hair('Hair_Gold',gold)}
assert body_positions==[tuple(v.co) for v in body.data.vertices]
assert body_weights==[[(g.group,g.weight) for g in v.groups] for v in body.data.vertices]
assert all(a==b.matrix_local for a,b in zip(bone_matrices,rig.data.bones))
