"""Recover Il's exterior paint and Habaru rock relief using the existing asset kit."""
import sys
from pathlib import Path
from PIL import Image
from build_coastal_villages import atlas
from build_freyja_destinations import load_map, IL_BUILDINGS, ALYUT_BUILDINGS
from build_freyja_surface import build as surface


def village(magic, output, ident, name, placements, profiles):
    sys.path.insert(0, str(magic / 'tools'))
    import cg_library as library
    lookup = library.serial_index()
    tiles = surface(magic, output, ident)
    w,h,ground,objects,_ = load_map(library,ident)
    rects = atlas(library,lookup,profiles,output/(name+'_buildings.png'),2048)
    grass = tiles[5045]
    rows=['extends RefCounted',f'## Generated by build_il_restoration.py from Blue CG map {ident}.',
          f'const GRASS_TILE=Vector2({grass%32},{grass//32})','const GRAPHICS={']
    for serial in profiles:
        e=lookup[serial];ew,ns=max(1,e['east']),max(1,e['south'])
        center=(-e['x']+(ew-ns)*16,-e['y']-(ew+ns-2)*12)
        rows.append(f' {serial}:[Rect2({",".join(map(str,rects[serial]))}),Vector2{center},Vector2({ew*3},{ns*3}),{e["h"]}],')
    rows+=['}','const PROFILES={',*[f' {s}:Vector2{p},' for s,p in profiles.items()],'}','const BUILDINGS={']
    available=[(i%w+(max(1,lookup[s]['east'])-1)*.5,i//w-(max(1,lookup[s]['south'])-1)*.5,s) for i,s in enumerate(objects) if s in profiles]
    used=set()
    for x,z in placements:
        chosen=min(available,key=lambda p:(p[0]-x)**2+(p[1]-z)**2)
        assert chosen not in used,(x,z,chosen)
        used.add(chosen)
        rows.append(f' Vector2({(x-w//2)*3},{(z-h//2)*3}):{chosen[2]},')
    assert len(used)==len(available)==len(placements)
    rows+=['}','const DETAILS=[']
    for i,s in enumerate(objects):
        asset='flowers_ivory' if 12169<=s<=12174 else 'flowers_coral' if 12175<=s<=12183 or s==10040 else 'grass_tall' if 11625<=s<=11679 else 'mossy_boulder' if 12107<=s<=12130 or 12225<=s<=12244 else ''
        if not asset:continue
        rows.append(f' [Vector2({(i%w-w//2)*3},{(i//w-h//2)*3}),"{asset}"],')
    rows+= [']']
    (output/(name+'_restoration_data.gd')).write_text('\n'.join(rows)+'\n')
    print(name, len(used), 'original building placements')


def build(magic, output):
    village(magic,output,2000,'il',[(x,z) for _,x,z,_,_ in IL_BUILDINGS],{11272:(140,120),11273:(145,120),11275:(145,120),11268:(160,120),10607:(220,85)})
    village(magic,output,2400,'alyut',list(ALYUT_BUILDINGS),{11272:(140,120),11275:(145,120),11271:(160,120),11269:(145,120)})
    faces=Image.open(output/'habaru_wall_faces.png').convert('RGBA')
    relief=['extends RefCounted','## Original cave wall luminance, using the existing undersea relief grid.','static var WALL_RELIEF={']
    for face in range((faces.width//36)*(faces.height//100)):
        if not faces.getchannel('A').crop((face%16*36,face//16*100,face%16*36+36,face//16*100+100)).getbbox():continue
        values=[]
        for height in (10,8.58,7.45,6.25,4.65,3.15,1.85,.66,0):
            for x in range(5):
                px=face%16*36+2+round(x*31/4);py=face//16*100+2+round((1-height/10)*95)
                pixel=faces.getpixel((px,py))
                values.append(round(.12+(1-sum(pixel[:3])/765)*.42,4))
        assert len(values)==45 and all(.12<=v<=.54 for v in values)
        relief.append(f' {face}:PackedFloat32Array({values}),')
    (output/'habaru_shapes.gd').write_text('\n'.join(relief+['}'])+'\n')
    from build_village_building_surfaces import build as building_surfaces
    building_surfaces(output)
    print('Il: 8 original building placements; Habaru:',len(relief)-3,'prepared rock faces')


if __name__=='__main__':
    build(Path(sys.argv[1]).resolve(),Path(__file__).resolve().parents[1]/'assets/maps/falan')
